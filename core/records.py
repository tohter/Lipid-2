"""
core/records.py — правила ЗАПИСИ и СЛИЯНИЯ записей об одной сущности.

Здесь живёт ОДНО место, где решается:
  * что вообще имеет право называться знанием (is_empty_entity);
  * какая категория является категорией, а какая — формой самого слова или
    служебным мусором Википедии (meaningful_categories);
  * что имеет право перезаписать известное (merge_entity);
  * как отсекает само обозначаемое слово из пояснения (strip_self_name).

Модуль чистый: stdlib, НИ ОДНОГО языкового импорта (шаг A2.2 границы: здесь
жил ленивый pymorphy3, теперь лемматизатор ПРИНОСЯТ извне через
set_lemma_service). Настоящее обоснование (ЗАМЕРЕНО, а
не «архитектурно правильно»): правило слияния нужно каналам знания, которые
обязаны работать на ЛЮБОМ python3. На системном python3 этой машины нет
numpy/scipy/torch/sentence_transformers/pymorphy3 — и import torch не происходит
вообще, потому что encoder.py обёрнут в try/except, а SentenceTransformer
импортируется лениво внутри метода. Тяжёлый стек включается в момент
КОДИРОВАНИЯ, а не импорта — и потому лёгкий канал обязан оставаться лёгким по
факту, а не по надежде.

pymorphy3 подключается лениво и по той же причине: без него сравнение форм
слов выродилось бы в отсечение окончаний, а оно (ЗАМЕРЕНО) путает
«кошка»/«кошачьи» — настоящую категорию — и не сводит «сеть»/«сети».
Сам ядро этот движок больше не зовёт: язык внедряет тот, кто имеет на это
право (brain/, lang/, инструмент). Внедрить забыли — не молчим, а орём.
"""
from __future__ import annotations

import re
import sys
from typing import Any, Callable, Dict, List, Optional

# Служебные категории Википедии. Это НЕ знание о предмете, а разметка статьи:
# «страницы значений», «требует викификации», «заготовка». ЗАМЕРЕНО в живом
# lipid_world.json: у сущности «ввод» иерархия состояла из
# «Страницы значений по алфавиту» — то есть ответ на «что такое ввод» был
# описанием того, как оформлена вики-страница.
_SERVICE_CATEGORY_RE = re.compile(
    r"(страниц[ыы] значени|значени[йи] по алфавиту|перенаправлени"
    r"|требующ[иие]е?\s+(викификаци|переписывания|уточнения|источников)"
    r"|стать[ыии].*(викификаци|переписывания|уточнения|без источников|к улучшению)"
    r"|заготовк[ии] (статей|статьи)|некатегоризированн|многозначн"
    r"|дисамбиг|ссылка[ии] на|неавторитетн|необходимо? проверит)",
    re.I,
)

# Слова, которые поясняют связь, но сами знания не содержат.
_LINK_WORDS = {"это", "есть", "является", "означает", "так", "то", "же", "или"}

# ── СЛУЖБА СВЕДЕНИЯ ФОРМ (граница языка, шаг A2.2) ───────────────────
#
# Здесь жил `import pymorphy3`. Это был язык внутри ядра: ядро само решало,
# куда деть русский падеж. По закону (experiments/IR_BOUNDARY.md §1) ядро не
# имеет права ни импортировать язык, ни знать, как его зовут, — поэтому
# лемматизатор СЮДА ПРИНОСЯТ: set_lemma_service().
#
# ПОЧЕМУ ОДИН УСТАНОВЩИК НА ПРОЦЕСС, А НЕ АРГУМЕНТ КАЖДОЙ ФУНКЦИИ. Функции
# records — свободные, их зовут 17 мест (замер AST), из них 6 производственных:
# мозг, ученик, core/storage, оба учителя, чистильщик мира. Протаскивать
# службу аргументом сквозь все шесть — значит получить шесть мест, где её
# можно забыть; ровно этот дефект A2.1 и поймал мутантом (мозг мог не передать
# резолвер, и весь набор тестов был зелёный). Ядро молча деградировало бы, а
# выглядело бы это как «в памяти ничего нет».
#
# ПОЭТОМУ: не принесли службу -> НЕ молчим. См. _warn_no_service().
_LEMMA_SERVICE: Optional[Callable[[str], str]] = None
_SERVICE_NAME = ""
_NO_SERVICE_WARNED = False
_LEMMA_CACHE: Dict[str, str] = {}


def set_lemma_service(lemma_fn: Callable[[str], str], *, name: str = ""):
    """
    Принести ядру лемматизатор: fn(слово) -> лемма | "" (empty = не знаю).

    Вызывать ОДИН раз на процесс, из слоя, который имеет право знать язык
    (brain/, lang/, инструмент). Повторный вызов разрешён: переключение
    службы — штатный случай теста и эксперимента.
    """
    global _LEMMA_SERVICE, _SERVICE_NAME, _NO_SERVICE_WARNED
    _LEMMA_SERVICE = lemma_fn
    _SERVICE_NAME = name or getattr(lemma_fn, "__qualname__", repr(lemma_fn))
    _NO_SERVICE_WARNED = False        # после установки обязаны замолчать
    _LEMMA_CACHE.clear()              # кэш грубой леммы протух
    return lemma_fn


def clear_lemma_service() -> None:
    """Убрать службу (тесты аварийного режима). Депродить без предупреждения
    нельзя: после этого любая лемма считается эвристикой и обязана кричать."""
    global _LEMMA_SERVICE, _SERVICE_NAME, _NO_SERVICE_WARNED
    _LEMMA_SERVICE = None
    _SERVICE_NAME = ""
    _NO_SERVICE_WARNED = False
    _LEMMA_CACHE.clear()


def lemma_service_state() -> dict:
    """Состояние службы — чтобы GUI и тесты могли сказать это ЧИСЛОМ, а не
    «кажется, морфология есть»."""
    return {"installed": _LEMMA_SERVICE is not None, "name": _SERVICE_NAME}


def _warn_no_service() -> None:
    """
    ГРОМКО и ОДИН РАЗ: формы слов сводим наивным отсечением.

    Молчание здесь стоило бы тихой деградации качества: без лемматизатора
    same_word уходит на эвристику (см. _lemma_simple), и часть полезных
    категорий начинает считаться «формой самого слова». Пользователь обязан
    видеть, что сравнение форм стало грубым, а не получать менее правильный
    ответ с тем же лицом.
    """
    global _NO_SERVICE_WARNED
    if _NO_SERVICE_WARNED:
        return
    _NO_SERVICE_WARNED = True
    print("[records] ⚠ СЛУЖБА СВЕДЕНИЯ ФОРМ НЕ ВНЕДРЕНА — сравнение форм слов "
          "ДЕГРАДИРОВАЛО до эвристики: часть полезных категорий будет принята "
          "за форму самого слова. Принести лемматизатор: "
          "core.records.set_lemma_service(fn). Язык умеет внедрять brain/ или "
          "lang/, ядро — нет.", file=sys.stderr, flush=True)


def _lemma_simple(word: str) -> str:
    """
    Лемма одного слова. Пустая строка — если определить нечего.

    Без морфологии — наивное отсечение: ЗАМЕРЕНО, что оно путает
    «кошка»/«кошачьи» (оба -> «кошк») и НЕ сводит «сеть»/«сети». Поэтому
    эвристика — аварийный режим, а не второй равный способ, и она обязана быть
    объявлена в stderr (см. _morph).
    """
    w = (word or "").strip().lower()
    if not w or not re.fullmatch(r"[а-яёa-z-]+", w):
        return ""
    cached = _LEMMA_CACHE.get(w)
    if cached is not None:
        return cached
    svc = _LEMMA_SERVICE
    if svc is not None:
        try:
            # normal_form, а НЕ normalform: AttributeError ловился общим except и
            # МОЛЧА превращал лемму в пустую строку, а пустая лемма значит
            # «это не то же слово» — тавтология переставала отфильтровываться.
            # Проверено на pymorphy3 4.0. Пустая строка от службы = «не знаю»,
            # это НЕ «не то же слово»: её отличает от ошибки только то, что
            # служба не упала.
            out = (svc(w) or "").lower()
        except Exception as exc:                    # pragma: no cover
            print(f"[records] ⚠ лемматизатор ({_SERVICE_NAME}) не разобрал "
                  f"«{w}»: {exc} — форма слова останется unrecognized",
                  file=sys.stderr, flush=True)
            out = ""
    else:
        _warn_no_service()
        out = w
        for suf in ("иями", "ями", "ами", "ов", "ев", "ам", "ям", "ов", "ей",
                    "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие", "ах", "ях",
                    "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими",
                    "ы", "и", "а", "я", "о", "е", "у", "ю", "ь"):
            if len(w) - len(suf) >= 3 and w.endswith(suf):
                out = w[:len(w) - len(suf)]
                break
    _LEMMA_CACHE[w] = out
    return out


def _norm_phrase(text: str) -> str:
    """Сравнительная форма фразы: без регистра и лишних пробелов."""
    return " ".join((text or "").lower().split())


def same_word(a: str, b: str) -> bool:
    """
    Одно ли это слово в разных формах. ТОЛЬКО один токен с каждой стороны.

    Фразы здесь сравнивать нельзя: pymorphy разбирает первый токен фразы, и
    «Луга Ленинградской области» дало бы лемму «луга», то есть настоящую
    категорию мы выбросили бы как тавтологию.
    """
    ta = (a or "").strip().split()
    tb = (b or "").strip().split()
    if len(ta) != 1 or len(tb) != 1:
        return False
    la, lb = _lemma_simple(a), _lemma_simple(b)
    if not la or not lb:
        return False
    if la == lb:
        return True
    # Эвристика работает ТОЛЬКО без морфологии: общий префикс не короче 4 букв
    # и не короче «короткое слово минус 2». С pymorphy3 она наоборот склеивала
    # бы разные слова («кошка»/«кошачьи» -> общий префикс «кошк»).
    if _LEMMA_SERVICE is not None:
        return False
    n = min(len(la), len(lb))
    return n >= 4 and la[:min(n, 4)] == lb[:min(n, 4)]


def _bracket_spans(text):
    """Интервалы скобочных вставок, вложенность учитывается.

    Нужен потому, что тире живёт не только в определениях, но и внутри
    этимологических скобок Википедии («(нид. Vleugel, нем. Flügel — крыло)»).
    Незакрытую скобку считаем открытой до конца строки: обрывок лида тоже
    обязан резаться по настоящей связке, а не по случайному тире.
    """
    spans = []
    stack = []
    for i, ch in enumerate(text):
        if ch in "([{«":
            stack.append(i)
        elif ch in ")])}»":
            if stack:
                spans.append((stack.pop(), i + 1))
    for i in stack:
        spans.append((i, len(text)))
    return spans


def strip_self_name(concept: str, text: str, min_rest: int = 3) -> str:
    """
    Отрезать от пояснения САМО ОБОЗНАЧАЕМОЕ СЛОВО, если оно стоит в начале.

    «Пчела — летаемое насекомое» — полный ответ на вопрос «что такое пчела», но
    первая его половина только повторяет заголовок. Перенесённое в иерархию как
    есть, оно склеивает ответ из двух имён: ЗАМЕРЕНО в GUI-прогоне —
    «Пчела — это Пчела — летаемое насекомое».

    min_rest: сколько обязано остаться, чтобы срез был осмысленным. Для
    определения Вики просят 15 (там остаток обязан быть фразой), для ответа
    пользователя достаточно слова «прибор» — он короток по сути.
    Если после среза остаётся снова название (или только связки) — срез
    бессмысленен и возвращаем исходник: тавтологию лучше видеть, чем прятать
    за пустотой, иначе «знания нет» маскируется обрезком.
    """
    out = " ".join((text or "").split())
    concept = (concept or "").strip()
    if not out or not concept:
        return out
    for _ in range(3):            # «X X — ...» редкость, но три повтора — потолок
        first = out.split(" ", 1)[0].strip(",.:;»\"")
        if not (same_word(first, concept) or first.lower() == concept.lower()):
            break
        # Разделитель ищется ВНЕ скобок. ЗАМЕРЕНО на живом канале: лида
        # «Флюгер (нид. Vleugel, нем. Flügel — крыло) — метеорологический
        # прибор…» давал ответ «Флюгер — крыло) — метеорологический прибор…",
        # потому что первое « — » стоит внутри этимологической скобки, а срез
        # по нему оставляет висячий «крыло)». Скобка — не часть определения,
        # резать по ней нельзя. Языковой список («лат.», «нид.», «нем.» …)
        # ДОКУПАТЬ НЕ СТАЛИ: он отсёк бы 0 новых случаев (замер по снимку
        # лидов), а маскирование скобок чинит класс целиком — тот же дефект
        # пришёл бы с «(англ. …)» или «(пол. …)».
        hide = _bracket_spans(out)
        cut = -1
        for sep in (" — ", " - ", " -- ", ": ", ", "):
            start = 0
            while True:
                pos = out.find(sep, start)
                if pos <= 0:
                    break
                if not any(a <= pos < b for a, b in hide):
                    cut = pos + len(sep)
                    break
                start = pos + 1
            if cut > 0:
                break
        rest = out[cut:].strip(" ,.:;—-") if cut > 0 else ""
        core_words = [w for w in rest.replace("—", " ").split()
                      if w.lower() not in _LINK_WORDS]
        if len(rest) < min_rest or not core_words \
                or all(same_word(w, concept) for w in core_words):
            break
        out = rest
    return out


def meaningful_categories(concept: str, hierarchy) -> list:
    """
    Оставить только настоящие категории. Убираются три вида мусора.

    1. Форма самого концепта («экосистема» -> «экосистемы»). Источник —
       Википедия: категория множественного числа есть у статьи почти всегда.
       ЗАМЕРЕНО: 4 из 6 реальных сущностей имели такую иерархию, и ответ
       звучал как «Экосистема — это экосистемы»: правдоподобно, пусто.
    2. Служебные категории Вики (_SERVICE_CATEGORY_RE) — разметка статьи.
    3. Дубли, совпавшие после нормализации регистра.

    Пустой список ЛУЧШЕ тавтологии: пустая иерархия уводит обработчик в ветку
    «данных нет», а тавтология притворяется ответом.
    """
    out: List[str] = []
    if not hierarchy:
        return out
    for raw in hierarchy:
        if not isinstance(raw, str):
            continue
        cat = raw.strip()
        if not cat:
            continue
        if _SERVICE_CATEGORY_RE.search(cat):
            continue
        if same_word(cat, concept):
            continue
        if cat.lower() == concept.lower():
            continue
        norm = _norm_phrase(cat)
        if any(norm == _norm_phrase(o) for o in out):
            continue
        out.append(cat)
    return out


def name_variants(entities: dict, observations: dict = None,
                  skip: Optional[str] = None) -> Dict[str, str]:
    """
    Карта «ВАРИАНТ ИМЕНИ -> канон» по всей Вселенной. ОДНА реализация.

    Два источника, оба — то, что УЖЕ лежит во Вселенной:
      1) поле "aliases" сущности (одно имя, два написания);
      2) наблюдения SYNONYM_OF (вариант -> канон), пережившие перезапись.

    ПОЧЕМУ ОДНА ФУНКЦИЯ НА ДВОИХ. Раньше карту строили два места, каждое у
    себя (ученик — для записи, и больше нигде), а мозг при ЧТЕНИИ не строил
    её вовсе: grep по brain/ на "aliases" был пуст. Следствие ЗАМЕРЕНО
    (04.11): «бегемот» с aliases:["гиппопотам"] на вопрос «гиппопотам»
    отвечал «не знаю», хотя знание лежало в файле; вторая сущность при этом
    не заводилась — то есть запись осталась одной, а доступ к ней пропал.
    Две копии карты означали бы два правила конфликта имён; правило одно,
    поэтому и код один.

    КОНФЛИКТ РАЗРЕШАЕТСЯ ПЕРВЫМ: если вариант уже привязан к другому канону,
    второй НЕ перетягивает (см. тот же закон в _record_aliases). Детерми-
    низм чтения важнее «угодить последнему»: без него один и тот же вопрос
    давал бы ответ про разные сущности в зависимости от обхода словаря.

    skip — имя, варианты которого не нужны (обычно сам канон: тесты и
    пересборка карты после правки записи).
    """
    skip_n = str(skip).lower().strip() if skip else ""
    out: Dict[str, str] = {}
    for name, ent in (entities or {}).items():
        canon = str(name).lower().strip()
        if not canon or canon == skip_n:
            continue
        for al in ((ent or {}).get("aliases") or []):
            al = str(al).lower().strip()
            if al and al != canon and al not in out:
                out[al] = canon
    for obs in (observations or {}).values():
        if not isinstance(obs, dict) or obs.get("negated"):
            continue
        if str(obs.get("relation", "")).upper() != "SYNONYM_OF":
            continue
        variant = str(obs.get("head", "")).lower().strip()
        canon = str(obs.get("tail", "")).lower().strip()
        if variant and canon and variant != canon and variant not in out:
            out[variant] = canon
    return out


def resolve_by_variant(name: str, entities: dict, variants: dict,
                       lemma_fn=None) -> Optional[str]:
    """
    Найти КАНОН по имени, которое может оказаться ВАРИАНТОМ (синонимом),
    в том числе в чужом падеже.

    Два шага, и порядок важен:
      1) точное совпадение с вариантом — самый дешёвый и самый точный;
      2) сведение формы — иначе «про гиппопотама» промахнётся, а именно так
         имена и приходят из речи.

    ПОЧЕМУ ШАГ 2 РАБОТАЕТ ТОЛЬКО НА НАСТОЯЩЕЙ МОРФОЛОГИИ. Если служба не
    принесли (см. _warn_no_service), форма считается наивным отсечением, и
    оно сводит РАЗНЫЕ слова: «кошка» и «кошачьи» -> «кошк». Для тавтологии
    в категориях это досадно, но здесь та же ошибка ОТВЕТИЛА БЫ ПРО ДРУГУЮ
    СУЩНОСТЬ. Ложный ответ дороже промаха (закон проекта: ложное ребро
    хуже отсутствующего), поэтому без морфологии остаётся шаг 1.

    Возвращает None, если это НЕ вариант известной сущности. Создавать узел
    здесь нельзя по тому же закону, что и в find_in_memory: промах обратим,
    слияние узлов — нет.
    """
    if not variants:
        return None
    name_n = str(name or "").lower().strip()
    if not name_n:
        return None
    hit = variants.get(name_n)
    if hit and hit in (entities or {}):
        return hit

    if lemma_fn is None:
        # Служба, принесённая в ядро (lang/ru). СВОЕЙ морфологии у ядра нет
        # и быть не может — см. experiments/IR_BOUNDARY.md §1.
        if _LEMMA_SERVICE is None:
            return None
        lemma_fn = _LEMMA_SERVICE
    try:
        form = str(lemma_fn(name_n) or "").lower().strip()
    except Exception as exc:                        # pragma: no cover
        print(f"[records] ⚠ лемматизатор не разобрал «{name_n}» при поиске "
              f"по варианту имени: {exc} — поиск останется по точной форме",
              file=sys.stderr, flush=True)
        return None
    if not form or form == name_n:
        return None
    for variant, canon in variants.items():
        if canon not in (entities or {}):
            continue
        try:
            v_form = str(lemma_fn(variant) or "").lower().strip()
        except Exception:                           # pragma: no cover
            return None
        if v_form and v_form == form:
            return canon
    return None


def is_empty_entity(rec) -> bool:
    """
    «Сущность есть в файле» и «о ней что-то известно» — РАЗНЫЕ утверждения.

    Пустая запись (только название) обязана отвечаться «знания нет». Пока она
    неотличима от знания, система отчитывается об успехе, записав одно слово, а
    пользователь получает строку из одного слова вместо ответа.
    """
    if not isinstance(rec, dict):
        return True
    for key in ("definition", "summary"):
        if str(rec.get(key) or "").strip():
            return False
    if rec.get("properties") or rec.get("actions") or rec.get("delta_properties"):
        return False
    if meaningful_categories(rec.get("concept") or "", rec.get("hierarchy")):
        return False
    return True


def action_name(action) -> str:
    """
    Имя действия из ЛЮБОЙ из двух форм, которые лежат в lipid_world.json:
    строка "бегать" и объект {"name": "бегать", "action_profile": [K, M, S]}.

    Профиль [K, M, S] — единственный носитель физического смысла действия для
    SDR-ядра, поэтому форму с профилем терять нельзя; но сравнивать действия
    надо по ИМЕНИ. Замер: у «гасить» в actions оказались {"name": "затухание"}
    и "затухание" рядом — слияние сверяло объект со строкой и видело два
    разных действия.
    """
    if isinstance(action, dict):
        return str(action.get("name") or "").strip()
    return str(action or "").strip()


def normalize_actions(actions) -> list:
    """Список действий -> без пустых и без повторов по имени (богатая форма
    сохраняется: словарь с action_profile не заменяется голой строкой)."""
    out: list = []
    index: dict = {}
    for a in (actions or []):
        name = action_name(a)
        if not name:
            continue
        low = name.lower()
        if low in index:
            # словари с профилем ценнее голой строки
            if isinstance(a, dict) and not isinstance(out[index[low]], dict):
                out[index[low]] = a
            continue
        index[low] = len(out)
        out.append(a)
    return out


def normalize_provenance(prov: Any, *, source: str = None) -> List[dict]:
    """
    ПРОИСХОЖДЕНИЕ К ЕДИНОЙ СХЕМЕ: список объектов, а не смесь строк и объектов.

    ПОЧЕМУ (очередь, п.14). В одном списке лежали И строки «wiki:Флюгер»
    (teachers/teacher_wiki.py), И объекты {source, evidence, at}
    (brain/learner.py, brain/lipid2_brain.py). Любой будущий код вида
    [(p["source"], p["at"]) for p in provenance] падает на строке — и падает
    НЕ на записи из Вики, а на первой попавшейся. Единая схема — объект:
        {"source": str, "evidence": str, "at": int|None}

    Строка разбирается по разделителю «:»: «wiki:Флюгер» ->
        {"source": "wiki", "evidence": "Флюгер"}.
    Строка без «:» — весь текст становится evidence, source берётся из
    аргумента source или пустой.
    """
    if prov is None:
        return []
    items = prov if isinstance(prov, list) else [prov]
    out: List[dict] = []
    for item in items:
        entry = _prov_entry(item, source)
        if entry is not None and entry not in out:
            out.append(entry)
    return out


def _prov_entry(item: Any, default_source: str = None) -> Optional[dict]:
    """Одна запись происхождения -> объект единой схемы (или None)."""
    if not item:
        return None
    if isinstance(item, dict):
        src = item.get("source")
        ev = item.get("evidence")
        at = item.get("at")
        # Незнакомые ключи не выбрасываем: расширение схемы не должно терять
        # данные, но базовые три поля приводим к единому виду.
        entry = dict(item)
        entry["source"] = str(src) if src else (default_source or "")
        entry["evidence"] = str(ev)[:200] if ev else ""
        if at is not None:
            try:
                entry["at"] = int(at)
            except (TypeError, ValueError):
                entry["at"] = None
        return entry
    # Строка вида "source:evidence" или просто "evidence"
    text = str(item).strip()
    if not text:
        return None
    if ":" in text:
        src, _, ev = text.partition(":")
        return {"source": src.strip() or (default_source or ""),
                "evidence": ev.strip()[:200], "at": None}
    return {"source": default_source or "", "evidence": text[:200], "at": None}


# СТАРШИНСТВО ДИАГНОЗОВ «не знаю» (очередь, п.15). Чем больше число, тем
# сильнее знание О НЕЗНАНИИ и тем меньше право его снять.
#   asked_empty — спросили честным вопросом и не нашли (сильнейшее: снимать
#                 его повторным спрашиванием = сжигать минуты на запрос);
#   action_no_profile — действие ждёт K/M/S (знание есть, профиля нет);
#   not_asked — не спрашивали (слабое: слово ОБЯЗАНО вернуться в очередь);
#   (нет статуса) — самое слабое (записи старше самого поля status).
UNKNOWN_STATUS_RANK = {"asked_empty": 3, "action_no_profile": 2,
                       "not_asked": 1}


def unknown_status_rank(status) -> int:
    """Сила диагноза «не знаю»; неизвестный/пустой статус — 0."""
    return UNKNOWN_STATUS_RANK.get(str(status), 0)


# ── ВЕС ФАКТА (УВЕРЕННОСТЬ) ═ ФОРМУЛА ОДНА, ЖИВЁТ ЗДЕСЬ ──────────────────
# Отношения, у которых верхняя половина шкалы (90..220), а не нижняя
# (60..160). Смысл: «что может / каким бывает» наблюдает текст напрямую,
# иерархию же приносят каналы знания, и шала на ней стоит дороже.
CONFIDENT_RELATIONS = ("CAN_DO", "HAS_PROPERTY")
# Прирост за повторное СВИДЕТЕЛЬСТВО (observations.support). Потолок 40:
# десятикратное повторение одного и того же рассказа не должно превращать
# догадку в неоспоримый факт — иначе один заученный текст перекрыл бы
# онтологию, проверенную двумя источниками.
SUPPORT_STEP = 10
SUPPORT_CAP = 40
# Делитель для отрицания. Отрицание — НЕ «знания нет», но и не уверенность:
# «кошка не боится воды» свидетельствует о связи слабее, чем утверждение.
NEGATION_DIVISOR = 3.0


def fact_weight(confidence: float, negated: Optional[bool] = None,
                relation: str = "", support: int = 1) -> int:
    """
    ЧИСЛО УВЕРЕННОСТИ в факте (0..255) — ЕДИНАЯ формула проекта.

    ЗАЧЕМ ОНА ПЕРЕЕХАЛА СЮДА (замер этой сессии). Формула жила приватным
    методом brain/learner.py::_weight. Из-за этого число «weight» не умел
    посчитать НИКТО, кроме обучающего, и оно НИКОГДА не попадало в
    observations — ЗАМЕРЕНО на живом мире: ключи записи head/relation/tail/
    confidence/negated/evidence/source/support/first_seen, ключа `weight` НЕТ.
    Следствие: brain/lipid2_brain.py::experience_conflicts() читает
    `v.get("weight", 0)` из этих записей, всегда получает 0 и никогда не
    выдаёт диагноз ontology_without_experience — канал, который выглядит
    работающим (тесты на него есть), был МЁРТВ. Формула в одном месте и
    доступная лёгким модулем — то, чего не хватало, чтобы её записали.

    Формула ПЕРЕНЕСЕНА БЕЗ ИЗМЕНЕНИЯ ЧИСЕЛ (brain/learner.py::_weight):
        CAN_DO / HAS_PROPERTY : 90 + 130*conf
        прочие                : 60 + 100*conf
        + min(40, 10*(support-1))
        при negated           : /3
       /clamp 8..255, int/
    Любая правка числа обязана идти от ЗАМЕРА и меняться ТОЛЬКО здесь.

    relation принимает ИМЯ отношения ("CAN_DO"), а не RelationType: лёгкий
    канал (системный python3, без numpy/torch) обязан считать тот же вес, что
    и ядро, иначе два писателя начнут расходятся числами.
    """
    try:
        conf = float(confidence)
    except (TypeError, ValueError):
        conf = 0.0
    conf = max(0.0, min(1.0, conf))
    rel = str(relation or "").upper()
    base = (90.0 + 130.0 * conf) if rel in CONFIDENT_RELATIONS \
        else (60.0 + 100.0 * conf)
    try:
        sup = int(support)
    except (TypeError, ValueError):
        sup = 1
    base += min(SUPPORT_CAP, SUPPORT_STEP * max(0, sup - 1))
    if negated:
        base /= NEGATION_DIVISOR
    return int(max(8, min(255, base)))


def observation_weight(obs: Optional[dict]) -> int:
    """
    УВЕРЕННОСТЬ в наблюдении (0..255) — В-store или ВЫВЕДЕННАЯ.

    ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, а не `obs.get("weight", 0)`. Ключ `weight` есть
    только у записей, написанных после этой правки; живой lipid_world.json
    старше него. Прямое .get(..., 0) на старых записях отдаёт НОЛЬ — и читатель
    делает вывод «факт совсем неуверенный», хотя правдивый ответ другой:
    «число не записано, но его надо вычислить». Это ровно тот класс лжи, что
    убил канал experience_conflicts (он читал weight из observations,
    вечно получал 0 и никогда не находил расхождение — ЗАМЕРЕНО).

    Поэтому: есть записанное число и ОН НАЗВАЛ ЗАКОН — берём его; иначе
    выводим. Число без имени закона есть самоотчёт канала (шаг 2.2/2.3):
    замер даёт ему 161..220 при одном основании, а права голоса у него нет.
    Ноль возможен только как настоящее 0, а не как «не спросили».

    СТАРЫЕ МИРЫ (записи до закона) читаются ПО ОСНОВАНИЮ КАНАЛА, а не по их
    confidence: ground у них есть, самоотчёт — то, от чего закон освобождает.
    """
    return record_weight(obs)


# ── ОСНОВАНИЕ ЗНАНИЯ (ground) ────────────────────────────────────────────
#
# ЧЕТЫРЕ ИМЕНИ — ИМЕНИ ТИПА ОСНОВАНИЯ, А НЕ ЧИСЛА. Числом владеть нельзя:
# «угольник — это треугольник» не бывает истинно на 0.3, а «собака — это
# животное» не обязано быть убедительнее определения.
GROUND_RULE = "rule"                    # формальное правило, вынесенное ПРОВЕРКОЙ
GROUND_OWNER = "owner"                  # слово Хозяина (источник назван)
GROUND_OBSERVATION = "observation"      # вычитано из текста (разбор)
GROUND_TESTIMONY = "testimony"          # чужой пересказ: Вики, модель
GROUNDS = (GROUND_RULE, GROUND_OWNER, GROUND_OBSERVATION, GROUND_TESTIMONY)
# Сила основания для сравнения «что сильнее» (НЕ вес и НЕ достоверность).
_GROUND_POWER = {GROUND_TESTIMONY: 0, GROUND_OBSERVATION: 1, GROUND_OWNER: 2,
                 GROUND_RULE: 3}
# ИМЕНА КАНАЛОВ. Именно от них зависит основание, а не от того, что канал
# о себе сказал. Таблица brain.CHANNEL_CONFIDENCE остаётся для разбора
# предложений; влиять на статус знания она больше не может.
_GROUND_BY_SOURCE = {
    "user": GROUND_OWNER, "owner": GROUND_OWNER,
    "text": GROUND_OBSERVATION, "story": GROUND_OBSERVATION,
    "replay": GROUND_OBSERVATION, "dream": GROUND_OBSERVATION,
    "wiki": GROUND_TESTIMONY, "wikipedia": GROUND_TESTIMONY,
    "llm": GROUND_TESTIMONY, "gemma": GROUND_TESTIMONY,
    "agent_teacher": GROUND_TESTIMONY, "teacher": GROUND_TESTIMONY,
}
# ПУТИ следования знания, а не его основания. Перенос из карантина ничего не
# утверждает об истинности — он говорит, ОТКУДА запись приехала в этот файл.
# Не сказать этого явно значило бы понести слово Хозяина до пересказа при
# первом же прохождении через единственную дверь записи.
_GROUND_PATHS = frozenset({"staged_candidate", "", "unknown"})


def ground_of(source: str, claimed: str = "") -> str:
    """Какое ОСНОВАНИЕ у знания, пришедшего от `source`.

    СЛОВО КАНАЛА НЕ ИМЕЕТ СИЛЫ. Аргумент `claimed` принят только для того,
    чтобы дыру можно было ЗАКРЫТЬ ТЕСТОМ: канал, заявивший «это аксиома»,
    обязан остаться свидетельством. Измерение 08.11: Gemma на 12 проверенных
    утверждениях поставила себе уверенность 1.00 на всех 12 (про бросок
    кубика она честно сказала 50%) — то есть самоотчёт есть громкость, а не
    проверка. Слово «правило» из уст учителя — тот же самоотчёт.

    `rule` отсюда НЕ ВЫВОДИТСЯ НИ ПРИ КАКОМ имени источника: его выносит
    только проверяющий механизм (реестр правил с тестом), и никакая строка
    "source" к нему не ведёт.

    Незнакомый канал идёт в testimony, а не в owner: «мы его просто пока не
    знаем» не есть основание доверять.
    """
    del claimed                                     # заявление канала
    key = str(source or "").strip().lower()
    if key.startswith("teacher:"):
        key = key.split(":", 1)[1].strip().lower()
    return _GROUND_BY_SOURCE.get(key, GROUND_TESTIMONY)


def record_ground(record: Optional[dict]) -> str:
    """Основание ЗАПИСИ, прочитанное из её коллекции свидетельств.

    ПОЧЕМУ НЕ ИЗ ПОЛЯ `ground` (возражение Жозефины, experiments/
    ADVISOR_GROUND_JO.txt, проверенное живьём). Одно поле на одно знание
    лжёт, потому что смешивает «кто сказал», «как получено» и «почему верим».
    Замер её предсказания: цепочка «статья Вики -> пересказ модели ->
    перефраз -> пересказ перефраза» подняла support 1 -> 5 и вес 160 -> 190,
    оставшись ОДНИМ независимым основанием.

    Поэтому первоисточник — КОЛЛЕКЦИЯ (верхний source + журнал provenance,
    оба уже пишутся), а `ground` — её прочтение: сильнейшее из оснований,
    каждое из которых помнит свой канал. Записанное поле `ground` —
    СПРАВКА для читателя, которое всегда можно пересчитать; оно не является
    доказательством самого себя (тест 6 это и проверяет).

    Разделение «потенциально независимых» оснований — следуюший кирпич, а
    не этот: здесь основание только перестаёт врать о себе.
    """
    if not isinstance(record, dict):
        return GROUND_TESTIMONY
    sources = []
    if record.get("source"):
        sources.append(str(record.get("source")))
    for prov in (record.get("provenance") or []):
        if isinstance(prov, dict) and prov.get("source"):
            src = str(prov["source"]).strip().lower()
            if src in _GROUND_PATHS:
                continue        # путь следования, а не свидетель
            sources.append(src)
    if not sources:
        return GROUND_TESTIMONY
    best = GROUND_TESTIMONY
    for src in sources:
        g = ground_of(src)
        if _GROUND_POWER[g] > _GROUND_POWER[best]:
            best = g
    return best


# ── ПРОИСХОЖДЕНИЕ СВИДЕТЕЛЬСТВА (lineage) ────────────────────────────
#
# ЗАЧЕМ. Кирпич 2 запретил греть связь от ПЕРЕСКАЗА, сравнивая КАНАЛ и
# ТЕКСТ. Жозефина (experiments/ADVISOR_GROUND_JO.txt) назвала это дыркой:
# «Система увидит четыре разных текста и два разных источника. На самом
# деле у неё может быть одно первоначальное основание». ЕЁ ПРЕДСКАЗАНИЕ
# ИЗМЕРЕНО ЖИВЬЁМ: цепочка «статья -> пересказ модели -> перефраз ->
# пересказ перефраза» подняла support 1 -> 5 и вес 160 -> 190 при ОДНОМ
# основании. Семь высказываний о связи «дождь CAN_DO гасить» (два рассказа,
# три канала-пересказа, слово Хозяина) дали support = 7 при ТРЁХ различных
# основаниях: четыре «подтверждения» нажиты одним способом производства.
#
# ПОЧЕМУ ЭТО НЕ ВЫДУМАННОЕ ПОЛЕ (замер). Происхождение УЖЕ есть в данных,
# но писатель его ВЫБРАСЫВАЕТ: учитель Википедии кладёт заголовок статьи в
# base_entity["title"], он доезжает до _record_observation в аргументе data
# и исчезает — в записи остаются head/relation/tail/confidence/evidence/
# source/support/ground/weight, ссылки на документ НЕТ. Назвать происхождение
# могут три канала из семи: Хозяин (он своё начало), статья Вики (заголовок
# есть), рассказ из файла (ЕСЛИ вызывающий назвал файл). У модели — НИЧЕГО:
# состав обучения неизвестен, и признать её ответ независимым от той же
# Википедии нечем.
INDEPENDENT = "independent"      # происхождение названо и встречается впервые
DEPENDENT = "dependent"          # такое происхождение уже было
UNKNOWN = "unknown"              # назвать нечем

# Хозяин здесь не документ: его слово является своим собственным началом,
# а не цитатой из чего-то.
_OWNER_SOURCES = frozenset({"user", "owner"})


def lineage_of(source: str, document: str = "") -> str:
    """Откуда ПРИЕХАЛО это свидетельство. Пустая строка = нечем назвать.

    ЗДЕСЬ НЕТ ВЫДУМКИ. Если документа нет, функция возвращает ПУСТО, а не
    канон из имени концепта: ЗАМЕРЕНО, что учитель Википедии знает заголовок
    своей статьи и передаёт его, а писатель терял. Выводить происхождение из
    head значило бы слить в одно основание статьи «Кит» и «Киты» — или
    раздвоить одну статью в двух каналах, как повезёт.

    КАНАЛ ВМЫСЛЕ НЕ ВХОДИТ (это не стиль, это измеренная дыра). Первая
    реализация делала ключ doc:<канал>:<документ>, и тест
    test_lineage_contract 9 поймал следствие: модель, объявившая источник
    «Кит», давала ОТДЕЛЬНОЕ основание рядом со статьёй «Кит», прочитанной
    нами, — то есть ровно то самое «четыре текста, одно основание», против
    чего весь механизм. Значит идентичность определяется ДОКУМЕНТОМ: кто
    именно его пересказал, записано в source отдельной строкой журнала.

    ЧЕСТНАЯ ЦЕНА: одно и то же имя у двух разных изданий («Кит» в Вики и
    «Кит» в словаре) сольётся в одно основание, и второе подтверждение мы
    потеряем. Теряем молчание, а не наживаем уверенность — по закону проекта
    это правильный край.

    Канал без документа НЕ получает «doc:<канал>»: «wiki» и «wiki» были бы
    тогда двумя основаниями, хотя это одна и та же статья, прочитанная
    дважды.
    """
    key = str(source or "").strip().lower()
    if key.startswith("teacher:"):
        key = key.split(":", 1)[1].strip().lower()
    if key in _OWNER_SOURCES:
        return "owner"
    doc = _norm_phrase(document)
    if not doc:
        return ""
    return f"doc:{doc}"


def independent_bases(record: Optional[dict]) -> int:
    """СКОЛЬКО РАЗЛИЧНЫХ ОСНОВАНИЙ стоит за связью — а не сколько строк.

    Это то, чем обязана питаться достоверность. Старый support считал
    СТРОКИ журнала: на измеренной цепочке это 7 строк против 3 оснований.
    """
    if not isinstance(record, dict):
        return 0
    bases = set()
    own = str(record.get("lineage") or "").strip()
    if own:
        bases.add(own)
    for prov in (record.get("provenance") or []):
        if isinstance(prov, dict):
            lin = str(prov.get("lineage") or "").strip()
            if lin:
                bases.add(lin)
    return len(bases)


