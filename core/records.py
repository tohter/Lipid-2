# СТАРАЯ ФОРМУЛА (90 + 130*conf) УМНОЖАЛА НА САМООТЧЁТ. Это не придуманная
# опасность, а ЗАМЕР experiments/measure_weight_authority.py (08.11 ночь):
#   * пять каналов с ОДНИМ основанием давали веса 161..220 — разброс 59
#     точек из 255 там, где основание ОДНО и различаются только числа,
#     которые каналы назвали О САМИХ СЕБЕ;
#   * безымянная модель с самоотчётом 1.00 (вес 220) перекрыла ДВЕ названные
#     книги (вес 171) — сила связи доставалась самой громкой;
#   * живой мир (data/memory/lipid_world.json.pre-clean): три связи с НУЛЁМ
#     названных оснований весили 120..210;
#   * ground не менял вес ВООБЩЕ: testimony, owner и rule давали одно число.
# Gemma на 12 проверенных утверждениях назвала себе 1.00 во всех 12
# (experiments/confidence_triage.py) — значит самоотчёт есть громкость.
#
# НОВЫЙ ЗАКОН: вес = сила ОСНОВАНИЯ + шаг за ОТДЕЛЬНОЕ ОСНОВАНИЕ. Число,
# которое канал сказал о себе, в вес не входит ни при каком основании.
# Потолок testimony (200) НИЖЕ порога консилиации (brain/sleep.py,
# CONFLICT_WEIGHT_MIN = 150). Одинокий пересказ обязан быть НИЖЕ порога,
# иначе диагноз «онтология без опыта» срабатывает на громкости, а не на
# пустом опыте — об этом TESTIMONY_LONE_MAX и тест на него.
# ГРАНИЦА (её надо помнить, замазывать нельзя): число оснований считает то,
# что НАЗВАНО. Незнание происхождения остаётся UNKNOWN, то есть молчанием в
# меньшую сторону. Мир мерит не лучше, чем ему рассказали.
GROUND_WEIGHT_LIFT = {
    GROUND_TESTIMONY: 40,
    GROUND_OBSERVATION: 110,
    GROUND_OWNER: 180,
    GROUND_RULE: 220,
}
# Прирост за каждое ОТДЕЛЬНОЕ основание (сверх первого). Шаг и потолок
# взяты из СМЫСЛА, а не из прежней шкалы: два независимых рассказа
# ощутимо сильнее одного, десятый — не в десять раз сильнее первого.
BASE_STEP = 20
BASE_CAP = 40
# Потолок чужого пересказа. ВЫШЕ порога конфликта (150) он обязан остаться
# ПОСЛЕ второго независимого основания, но ОДИНОКИЙ пересказ обязан быть
# ниже — иначе диагноз «онтология без опыта» становится недостижим, а это
# ровно тот мёртвый канал, который чинили замером (см. fact_weight).
TESTIMONY_LONE_MAX = 140
# Ступень «НАЗВАТЬ НЕЧЕМ». Отношение оснований (bases=0) — UNKNOWN из
# кирпича 6: канал есть, источника не названо. Такая связь обязана стоить
# ДОШЕВ названной: иначе у писателя нет никакой выгоды назвать документ, а
# кирпич 6 обещал, что называние имеет цену. Замер до правки этой ступени:
# «дождь|CAN_DO|гасить» из статьи (названной) и из безымянной модели давали
# ОДНО число 40 — то есть закон происхождения не менял ничего.
UNKNOWN_LIFT_DIVISOR = 2.0
# ЧИСЛО ОБЯЗАНО НОСИТЬ ИМЯ ЗАКОНА, ПО КОТОРОМУ ОНО ПОСЧИТАНО. Читатель
# верит записанному весу ТОЛЬКО если закон назван: иначе самоотчёт вернулся
# бы через дверь «у записи уже лежит weight», а закон против него и написан.
# Записи, посеянные СТАРЫМ законом (90 + 130*самоотчёт), поля не имеют — их
# число при чтении ВЫВОДИТСЯ заново, то есть ложное право голоса умирает при
# чтении, а не ждёт, пока запись перезапишут.
GROUND_WEIGHT_LAW = "ground-v2"           # посчитано силой основания
EXPERIENCE_WEIGHT_LAW = "experience-v1"   # посчитано из силы ОПЫТА (сон)
LAWFUL_WEIGHTS = (GROUND_WEIGHT_LAW, EXPERIENCE_WEIGHT_LAW)


def weight_from_ground(ground: str, bases: int = 1,
                       negated: Optional[bool] = None) -> int:
    """Вес связи ПО СИЛЕ ОСНОВАНИЯ, без самоотчёта канала.

    ЧЕГО ЗДЕСЬ НЕТ и почему. `confidence` сюда не передаётся ВООБЩЕ — не
    «умножается меньше», а отсутствует в сигнатуре: пока параметр есть,
    какой-нибудь писатель обязательно подставит в него самоотчёт, и закон
    деградирует до прежнего молча. Пустая сигнатура — единственный способ
    сделать дыру недоступной, а не нежелательной.

    Отрицание остаётся ДЕЛИТЕЛЕМ (3), а не нулём: «кошка не боится воды»
    свидетельствует о связи слабее утверждения, но свидетельствует.
    """
    ключ = str(ground or "").strip().lower()
    lift = GROUND_WEIGHT_LIFT.get(ключ, GROUND_WEIGHT_LIFT[GROUND_TESTIMONY])
    try:
        n = int(bases)
    except (TypeError, ValueError):
        n = 0
    if n <= 0:
        # Назвать основание нечем. Считаем ПОЛОВИНОЙ силы того типа канала,
        # которым он назвался: «вычитано из какого-то текста» — не «вычитано
        # из книги N» и не «мне кажется». Молчание в меньшую сторону —
        # сознательный выбор: молчать дороже, чем соврать в большую силу.
        base = lift / UNKNOWN_LIFT_DIVISOR
        if negated:
            base /= NEGATION_DIVISOR
        return int(max(8, min(255, base)))
    step = 0 if n == 1 else BASE_STEP * (n - 1)
    if str(ground or "").strip().lower() == GROUND_TESTIMONY:
        # ОДИНОКИЙ пересказ не перешагивает порог конфликта. Замер 08.11:
        # до этой правки testimony с одним основанием давал 174..220 и
        # диагноз ontology_without_experience срабатывал на ПУСТОМ опыте
        # ровно потому, что пересказ был громким, а не обоснованным.
        step = min(step, BASE_CAP)
        base = min(lift + step, TESTIMONY_LONE_MAX) if n <= 1 \
            else min(lift + step, 255)
    else:
        base = lift + min(step, BASE_CAP)
    if negated:
        base /= NEGATION_DIVISOR
    return int(max(8, min(255, base)))


def record_weight(record: Optional[dict]) -> int:
    """Вес ЗАПИСИ наблюдения: от основания и числа отдельных оснований.

    Записанное как есть берётся ТОЛЬКО число сна (EXPERIENCE_WEIGHT_LAW): у
    него единственный источник — сила опыта, а её в самой записи нет, так что
    пересчитать её на месте невозможно. Вес основания (GROUND_WEIGHT_LAW)
    ВЫВОДИТСЯ заново всегда: он полностью производится из ground и оснований,
    а держать его кэшом значило бы переживать рассинхронизацию двух чисел
    вместо одного источника. Прочее число — самоотчёт канала, у самоотчёта
    права голоса нет (замер: 161..220 при ОДНОМ основании).

    ПОЧЕМУ ЧИТАЕТСЯ ЧИСЛО СНА, а не max(выведенный, записанный). Замер
    прошлой сессии (brain/learner.py::replay): сон понизил вес 220 -> 190 в
    данных, а replay пересчитывал по формуле и возвращал 210 — понижение
    опыта НИКОГДА не доходило до графа, оставаясь правкой JSON, которую
    никто не читает. max повторил бы ровно ту ошибку: «улучшить» число
    нельзя ценой отмены понижения, потому что понижение и есть результат
    опыта.
    """
    if not isinstance(record, dict):
        return 0
    # ОСНОВАНИЕ БЕРЁТСЯ ИЗ КОЛЛЕКЦИИ, а не из поля `ground`. Поле — СПРАВКА
    # для читателя (закон кирпича 5: «оно не является доказательством самого
    # себя»), и доверять ему при выводе веса значило бы молча отдать право голоса устаревшей строке
    # решала, сколько знания стоит. ЗАМЕРЕНО: запись со source="user" и
    # lineage="owner", унаследовавшая "ground": "testimony" от прежнего
    # канала, давала вес 40 вместо 180 — то есть слово Хозяина теряло силу
    # МОЛЧА, только потому, что кто-то раньше записал другой статус.
    ground = record_ground(record)
    # bases = 0 ОСТАЁТСЯ нулём и передаётся в weight_from_ground: там для
    # него есть отдельная ступень. Подменить на единицу значило бы сравнять
    # «не знаю откуда» с «знаю откуда ровно один раз» — а тогда называть
    # источник писателю невыгодно и кирпич 6 повисает без последствия.
    bases = independent_bases(record)
    законно = str(record.get("weight_law") or "") == EXPERIENCE_WEIGHT_LAW
    выведенный = weight_from_ground(ground, bases, record.get("negated"))
    if законно:
        raw = record.get("weight")
        if not isinstance(raw, bool):
            try:
                # ЧИСЛО ОПЫТА ПРИНАДЛЕЖИТ ОПЫТУ ЦЕЛИКОМ, а не берётся как
                # max с подъем основанием. Замер max(): сон понижал вес связи
                # слова Хозяина 180 -> 150, читатель возвращал 180, и понижение
                # НЕ ДОХОДИЛО до графа НИКОГДА — тот же дефект, что лечили
                # allow_lower в replay (молча no-op), только с другой стороны.
                # Основание задаёт СТАРТОВЫЙ вес, пока сон о нём не высказался;
                # после высказывания опыт имеет право и поднять, и опустить.
                return min(255, max(0, int(raw)))
            except (TypeError, ValueError):
                pass                          # кривое число — выводим, не нулим
    return выведенный


def witness_state(record: Optional[dict], source: str, evidence: str,
                  document: str = "") -> str:
    """INDEPENDENT / DEPENDENT / UNKNOWN для предстоящего свидетельства.

    UNKNOWN ОТДЕЛЁН от DEPENDENT намеренно (состояние придумала не я, а
    Жозефина, и цена у него другая): зависимость НЕ УСТАНОВЛЕНА — это не
    «тот же документ», а «мы не знаем». Такое свидетельство СОХРАНЯЕТСЯ
    (его ещё можно перепроверить, когда происхождение выяснится), но НЕ
    греет: необоснованное повышение доверия и есть самообман.
    """
    lin = lineage_of(source, document)
    if not lin:
        return UNKNOWN
    if not isinstance(record, dict):
        return INDEPENDENT
    if str(record.get("lineage") or "").strip() == lin:
        return DEPENDENT
    for prov in (record.get("provenance") or []):
        if isinstance(prov, dict) and \
                str(prov.get("lineage") or "").strip() == lin:
            return DEPENDENT
    return INDEPENDENT


def stamp_ground(record: dict) -> dict:
    """Записать в запись её основание и ВЕС, вычислив их, а не приняв на веру.

    Поле перечисляется ПОСЛЕ того, как коллекция собрана, и ПЕРЕЗАПИСЫВАЕТ
    любое значение, приехавшее извне: пакет учителя со словом "rule"
    обязан выйти из функции со статусом свидетельства.

    ПОЧЕМУ ЗДЕСЬ ЖЕ И ВЕС (замер мутированием, 08.11 шаг Г). Функция
    существовала, была заперта тестом и НЕ ВЫЗЫВАЛАСЬ НИКЕМ: три места
    записи сами писали "ground": ground_of(source) и сами считали вес.
    Мутация «принять приехавшее ground» выживала ровно потому, что
    охраняемый код был мёртв, — тест защищал функцию, которой никто не пользуется.
    Теперь основание и вес ставит ОДНА функция, и дыра закрывается в одном
    месте, а не в трёх.

    ВЕС НЕ ТРОГАЕТСЯ, если его закон — сила опыта: число, посчитанное сном
    из силы опыта, не имеет права быть перезаписанным основанием (тот же
    закон, что в add_witness и merge_observation).
    """
    if isinstance(record, dict):
        record["ground"] = record_ground(record)
        if str(record.get("weight_law") or "") != EXPERIENCE_WEIGHT_LAW:
            record["weight"] = weight_from_ground(
                record["ground"], independent_bases(record),
                record.get("negated"))
            record["weight_law"] = GROUND_WEIGHT_LAW
    return record


def same_witness(obs: Optional[dict], source: str, evidence: str) -> bool:
    """То ли это СВИДЕТЕЛЬСТВО, что уже лежит в записи, или пересказ.

    Совпали И канал, И основание (текст-доказательство) — перед нами тот же
    самый опыт, рассказанный второй раз.
    """
    if not isinstance(obs, dict):
        return False
    src = _norm_phrase(source)
    ev = _norm_phrase(evidence)
    # ПЕРВОЕ свидетельство обучающий из рассказов держит ВЕРХНИМ УРОВНЕМ
    # (source/evidence у самой записи), а не в журнале provenance. Сверять
    # только журнал значило бы признать ПЕРЕСКАЗ новым подтверждением у того
    # писателя, который журнала не ведёт, — то есть ровно там, где дыра и
    # была измерена.
    if (src and _norm_phrase(obs.get("source", "")) == src
            and _norm_phrase(obs.get("evidence", "")) == ev):
        return True
    for prov in (obs.get("provenance") or []):
        if not isinstance(prov, dict):
            continue
        if _norm_phrase(prov.get("source", "")) != src:
            continue
        if _norm_phrase(prov.get("evidence", "")) == ev:
            return True
    return False


def add_witness(obs: dict, *, source: str, evidence: str, confidence: float,
                negated: bool = False, relation: str = "",
                at: Optional[int] = None, document: str = "") -> bool:
    """
    Одно СВИДЕТЕЛЬСТВО к уже существующей связи. Возвращает True, если
    достоверность выросла, False — если это ПЕРЕСКАЗ или НЕИЗВЕСТНО ОТКУДА.

    ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В ПИСАТЕЛЯХ (слова Хозяина 08.11 +
    замер живьём). Хозяин запретил превращать одну историю в пожизненное
    ребро. А замер дал обратное: ОДНА И ТА ЖЕ фраза «Дождь гасит огонь.»,
    прогнанная через обучающий трижды, подняла support 1 -> 2 -> 3 и вес
    200 -> 210 -> 220. Ни одного нового наблюдения в мире не было — мир не
    двигался; движение было только в процессе, и оно превратилось в
    убеждённость. Раньше это охранял тест с формулировкой «два независимых
    свидетельства», где независимость была СЛОВОМ: подавалась одна фраза с
    одним source. Правило в двух писателях (brain и learner) неизбежно
    расходится — этот класс дыр мы чинили кирпичом раньше, поэтому закон
    стоит в одном месте и вызывается обоими.

    ОТДЕЛЬНЫМ считалось свидетельство, у которого отличается ИСТОЧНИК или
    ОСНОВАНИЕ (кирпич 2). Этого оказалось мало, и это измерено, а не
    угадано: Жозефина предсказала, что четыре текста с одним первоначальным
    основанием дадут четыре подтверждения. Прогнано живьём — цепочка «статья
    Вики -> пересказ модели -> перефраз -> пересказ перефраза» подняла
    support 1 -> 5 и вес 160 -> 190. Отличие текстов не спорно: пересказ
    отличается от оригинала ВСЕГДА.

    НОВОЕ ПРАВИЛО: греет только НЕЗАВИСИМОСТЬ, которую можно НАЗВАТЬ
    (lineage_of). Совпало происхождение — DEPENDENT, не греет. Назвать
    нечем — UNKNOWN, тоже не греет, но свидетельство ОСТАЁТСЯ в журнале:
    мы отказываемся от необоснованного повышения доверия, но не от данных,
    которые можно перепроверить, когда происхождение выяснится.

    ЦЕНА ПРАВИЛА (замерена ДО правки, слова Хозяина 08.11: «поехали»).
    На семи высказываниях о «дождь CAN_DO гасить» support 7 -> 3; на цепочке
    пересказов 5 -> 1. Молчание каналов без документа (модель, безымянный
    текст) становится нормой: их ответы больше НИКОГДА не поднимут
    достоверность сами по себе. Мы теряем часть подтверждений — и никогда не
    наживаем ложную уверенность: ложная связь хуже пропущенной (закон
    проекта), а ложная уверенность в связи хуже молчаливой дыры, потому что
    её нечем перепроверить — число выглядит заработанным.
    """
    lineage = lineage_of(source, document)
    state = witness_state(obs, source, evidence, document)
    if same_witness(obs, source, evidence):
        # Дословное повторение того же опыта. Новую строку в журнал не
        # пишем: строка, которая ничего не измеряет, раздувает то самое
        # число, против которого весь механизм.
        # ЕДИНСТВЕННОЕ исключение — УТОЧНЕНИЕ ДАННЫХ: раньше происхождение
        # назвать было нечем, теперь есть чем. Иначе обещание «UNKNOWN
        # сохраняется и будет пересмотрено» осталось бы текстом —
        # переклассифицировать строку было бы нечем. ДОСТОВЕРНОСТЬ ЭТО НЕ
        # ГРЕЕТ: число подтверждений остаётся числом подтверждений, мы лишь
        # перестали притворяться, что не знаем, откуда строка приехала.
        if not lineage:
            return False
        touched = False
        # ВЕРХНИЙ УРОВЕНЬ ЗАПИСИ. Первый свидетель у обучающего хранится
        # не в журнале, а полями source/evidence самой записи. Замер 08.11:
        # поиск только по журналу делал уточнение ВЕРХНЕГО уровня
        # невозможным — то есть «назови происхождение позже» работало лишь
        # для второго и дальше свидетельства, а первое оставалось вечно
        # безымянным.
        if (not str(obs.get("lineage") or "").strip()
                and _norm_phrase(obs.get("source", "")) == _norm_phrase(source)
                and _norm_phrase(obs.get("evidence", "")) == _norm_phrase(evidence)):
            obs["lineage"] = lineage
            touched = True
        for prov in (obs.get("provenance") or []):
            if not isinstance(prov, dict):
                continue
            if _norm_phrase(prov.get("source", "")) != _norm_phrase(source):
                continue
            if _norm_phrase(prov.get("evidence", "")) != _norm_phrase(evidence):
                continue
            if not str(prov.get("lineage") or "").strip():
                prov["lineage"] = lineage
                touched = True
        if not touched:
            return False
        if not str(obs.get("lineage") or "").strip():
            obs["lineage"] = lineage
        # ЕДИНОЕ ПРАВИЛО ЗАСЧЁТА (и оно же отвечает на вопрос «зачем тогда
        # хранить UNKNOWN»): подтверждение засчитывается ОДИН РАЗ — в момент,
        # когда независимость НАЗВАНА. Пришла строка без происхождения —
        # молчим; назвали её позже тем же документом — вот теперь зачёт, и
        # ровно один. Если бы зачёт не происходил вовсе, смысл хранить
        # неопознанное свидетельство терялся бы: число навсегда осталось бы
        # враньём в меньшую сторону, а Вранье в большую мы как раз лечим.
        if state == INDEPENDENT:
            # SUPPORT = ЧИСЛО ОСНОВАНИЙ, а не счётчик прибавлений. Прирост
            # "+1" давал расхождение, замеренное experiments/
            # measure_support_vs_bases.py: безымянная строка создана с
            # support=1, её же называние документом прибавляло второй —
            # «видела 2 раза» при ОДНОМ названном основании. То же враньё,
            # ради которого писался кирпич 6, только в другом поле.
            obs["support"] = max(1, independent_bases(obs))
            obs["ground"] = record_ground(obs)
            obs["weight"] = weight_from_ground(
                obs["ground"], independent_bases(obs), obs.get("negated"))
            obs["weight_law"] = GROUND_WEIGHT_LAW
            return True
        obs["ground"] = record_ground(obs)
        return False
    prov = obs.setdefault("provenance", [])
    entry = {"source": source or "unknown", "evidence": (evidence or "")[:200]}
    # Происхождение пишется В ЖУРНАЛЕ и дописывается в верх записи, а не
    # ЗАМЕНЯЕТ его: запись обязана помнить и первое основание, и все
    # пришедшие позже, иначе independent_bases() видит только последнее.
    if lineage:
        entry["lineage"] = lineage
    if at is not None:
        entry["at"] = int(at)
    prov.append(entry)
    if lineage and not str(obs.get("lineage") or "").strip():
        obs["lineage"] = lineage
    # Уверенность берём ЛУЧШЕЕ из свидетельств, а не последнее: второй проход
    # с более слабым разбором не должен отменять уверенный.
    obs["confidence"] = max(float(obs.get("confidence", 0.0)),
                            float(confidence))
    if negated:
        obs["negated"] = True
    # ЕДИНСТВЕННОЕ МЕСТО, где растёт достоверность: только НАЗВАННАЯ
    # независимость. UNKNOWN и DEPENDENT проходят мимо — свидетельство уже
    # лежит в журнале выше, но числа не касается.
    if state == INDEPENDENT:
        obs["support"] = int(obs.get("support", 1)) + 1
    # ОСНОВАНИЕ ПЕРЕСЧИТЫВАЕТСЯ ПОСЛЕ КАЖДОГО СВИДЕТЕЛЯ, а не берётся из
    # приехавшего поля: иначе канал, приславший "ground": "rule", стал бы
    # правилом (тест 6). Рост support сам по себе статуса НЕ даёт — за это
    # отвечает record_ground, который смотрит на каналы, а не на их число.
    obs["ground"] = record_ground(obs)
    # ВЕС ПЕРЕСЧИТЫВАЕТСЯ ПОСЛЕ КАЖДОГО СВИДЕТЕЛЯ и порождается ОСНОВАНИЕМ, а
    # не самоотчётом канала (шаг 2.2/2.3 босса). Старая формула
    # fact_weight(confidence, ...) делала силу связи функцией того, НАСКОЛЬКО
    # УВЕРЕННО канал высказался: замер даёт веса 161..220 при ОДНОМ
    # основании и 220 у модели без основания против 171 у двух названных
    # книг (experiments/measure_weight_authority.py). Отношение к формуле
    # больше не передаётся: «умеет/бывает» не бывает достовернее слова
    # Хозяина только потому, что так назвали отношение.
    # SUPPORT ПЕРЕСЧИТЫВАЕТСЯ ПОСЛЕ КАЖДОГО СВИДЕТЕЛЯ по тому же основанию,
    # что и вес: одно число «видела N раз» на два читателя (certainty и вес)
    # обязано значить одно и то же. Молчание в меньшую сторону сохраняет
    # единицу: знание мы НЕ отменяем, мы перестаём приписывать ему чужую
    # поддержку.
    obs["support"] = max(1, independent_bases(obs))
    if str(obs.get("weight_law") or "") != EXPERIENCE_WEIGHT_LAW:
        obs["weight"] = weight_from_ground(obs["ground"],
                                           independent_bases(obs),
                                           obs.get("negated"))
        obs["weight_law"] = GROUND_WEIGHT_LAW
    # ИНАЧЕ ЧИСЛО ПРИНАДЛЕЖИТ ОПЫТУ. Понизить его имеет право сон, когда
    # опыт молчит об «умеет»; пересчитать его по основанию — нет, иначе
    # каждое новое свидетельство стирало бы понижение молча, а это ложная
    # уверенность (опыт-то не вернулся). Поднять число сможет снова сон,
    # когда опыт ЗАГОВОРИТ (правило подтверждения consolidation).
    return state == INDEPENDENT


def merge_observation(cur: dict, incoming: dict) -> dict:
    """Слить ДВА снимка ОДНОЙ связи (чужой процесс писал тот же файл).

    ПРАВИЛО ЖИВЁТ ЗДЕСЬ, а не в писателе, по той же причине, по которой
    рядом живёт add_witness: brain/learner.py держал свою копию слияния и
    переносил из неё support/confidence/negated, а ПРОИСХОЖДЕНИЕ И ЖУРНАЛ —
    НЕТ. Замер 08.11: отказавшее (независимость не названа) свидетельство
    добавлялось в память, а после записи на диске его не оказывалось — то
    есть обещание «сохраняем и перепроверим позже» было текстом. Молча
    потерянные данные хуже потерянных громко: их некому восстановить.

    support после слияния — НЕ сумма и не «+1": это число засчитанных
    подтверждений, и оно обязано согласоваться с числом РАЗЛИЧНЫХ
    названных оснований в объединённом журнале (иначе два процесса,
    независимо засчитавшие одно и то же основание, удвоили бы его).
    """
    if not isinstance(cur, dict):
        return incoming
    if not isinstance(incoming, dict):
        return cur
    cur["support"] = max(int(cur.get("support", 1)),
                         int(incoming.get("support", 1)))
    cur["confidence"] = max(float(cur.get("confidence", 0)),
                            float(incoming.get("confidence", 0)))
    cur["negated"] = bool(cur.get("negated")) or bool(incoming.get("negated"))
    # ЖУРНАЛ и ПРОИСХОЖДЕНИЕ — аддитивно, по той же цене, что события и
    # ожидания ниже по файлу: чужой рассказ не должен теряться.
    seen = {(_norm_phrase(str(p.get("source", ""))),
             _norm_phrase(str(p.get("evidence", ""))))
            for p in (cur.get("provenance") or []) if isinstance(p, dict)}
    prov = cur.setdefault("provenance", [])
    for p in (incoming.get("provenance") or []):
        if not isinstance(p, dict):
            continue
        mark = (_norm_phrase(str(p.get("source", ""))),
                _norm_phrase(str(p.get("evidence", ""))))
        if mark in seen:
            continue
        seen.add(mark)
        prov.append(p)
    if not str(cur.get("lineage") or "").strip():
        cur["lineage"] = str(incoming.get("lineage") or "").strip()
    # ПОДДЕРЖКА СЛИТОЙ ЗАПИСИ = число отдельных оснований, с сохранённым
    # floor 1: два процесса могли независимо засчитать одно основание, и
    # max(support, bases) оставил бы «видела 2 раза» на одном документе.
    cur["support"] = max(1, independent_bases(cur))
    # weight ПЕРЕСЧИТЫВАЕТСЯ от слитых полей, а не хранится «максимумом
    # двух весов»: weight — ПРОИЗВОДНАЯ от (confidence, support, negated).
    # При ОТРИЦАНИИ пересчёт обязывает число УПАСТЬ: иначе высокий вес
    # остался бы лежать рядом с negated=True — тихая порча, из-за которой
    # формулу и перенесли в данные.
    cur["ground"] = record_ground(cur)
    # ВЕС СЛИТОЙ ЗАПИСИ считается ОТ ОСНОВАНИЯ И ЧИСЛА ОСНОВАНИЙ, а не
    # «максимумом двух чисел»: max отменил бы понижение, положенное сном,
    # и дало бы выигрыш тому снимку, где канал был громче. Закон-источник
    # сохраняется ТОЛЬКО если его не пришлось пересчитать: число сна
    # (опыт) пересчёт по основанию не отменяет, и наоборот.
    if str(cur.get("weight_law") or "") == EXPERIENCE_WEIGHT_LAW:
        pass       # число положено СИЛОЙ ОПЫТА: пересчёт по основанию опыта
                   # не знает и отменить понижение сном не имеет права
    else:
        cur["weight"] = weight_from_ground(cur["ground"],
                                           independent_bases(cur),
                                           cur.get("negated"))
        cur["weight_law"] = GROUND_WEIGHT_LAW
    return cur


def merge_unknown_entry(prev: Optional[dict], new: Optional[dict]) -> dict:
    """
    СЛИЯНИЕ двух записей unknown_words ОДНОГО слова (очередь, п.15).

    ПОЧЕМУ. При слиянии двух снимков мира статус выбирался ФАКТИЧЕСКИ по
    порядку чтения (кто последний — тот и прав), а count брали max. Из-за
    этого правильный диагноз asked_empty мог быть завален старым not_asked,
    и слово возвращалось в очередь урока — или наоборот, снимался неверный
    asked_empty с глагола. Оба направления ЗАМЕРЕНЫ в проекте как ошибки.

    Правило: остаётся САМЫЙ СИЛЬНЫЙ диагноз (см. UNKNOWN_STATUS_RANK), а
    count — максимум. При равной силе побеждает новый (у него свежее
    status_note/reason).
    """
    prev = prev if isinstance(prev, dict) else {}
    new = new if isinstance(new, dict) else {}
    if not prev:
        return dict(new)
    if not new:
        return dict(prev)
    merged = dict(prev)
    # count — максимум: счётчик обращений не зависит от порядка снимков.
    merged["count"] = max(int(prev.get("count", 1)), int(new.get("count", 1)))
    rp, rn = unknown_status_rank(prev.get("status")), unknown_status_rank(new.get("status"))
    if rn > rp:
        winner, loser = new, prev
    elif rn < rp:
        winner, loser = prev, new
    else:
        winner, loser = new, prev          # равная сила — свежее важнее
    for k, v in winner.items():
        if k == "count":
            continue
        if v not in (None, "", [], {}):
            merged[k] = v
    # Поля проигравшего, которых нет у победителя, НЕ теряем: reason/seen_as
    # могут нести факты, которых у победителя нет вообще.
    for k, v in loser.items():
        if k == "count" or k in merged:
            continue
        if v not in (None, "", [], {}):
            merged[k] = v
    return merged


def merge_entity(prev: Optional[dict], new: dict) -> dict:
    """
    СЛИЯНИЕ ДВУХ ЗАПИСЕЙ ОДНОЙ СУЩНОСТИ. ОДНА РЕАЛИЗАЦИЯ ДЛЯ ВСЕХ.

    Правило: новое имеет право ДОБАВИТЬ, но не имеет права СТЕРЕТЬ.
    Списки (hierarchy/properties/actions/delta_properties) объединяются без
    повторов, скалярное поле заменяется только если было пустым.

    Почему это вынесено сюда: запись об одной сущности приходит из четырёх мест
    (base/derived от локалки, Википедия, ответ пользователя, извлечение из
    текста), и в трёх из них раньше был СВОЙ вариант слияния. Каждый терял
    данные по-своему: `world[concept] = base` перезаписывал насыщенную запись
    вырожденной, а порядок вызовов продюсера стирал иерархию.

    Здесь же чистится иерархия — с ОБЕИХ сторон. Чистить только «новое»
    бессмысленно: тавтология, уже лежащая в файле, пережила бы сколько угодно
    правок (замерено на реальном lipid_world.json).
    """
    if not isinstance(new, dict):
        return prev if isinstance(prev, dict) else {}
    merged = dict(prev) if isinstance(prev, dict) else {}
    # "aliases" обязан быть здесь: без этого второе имя сущности терялось при
    # первом же слиянии (правило «не перезаписывать непустое» оставило бы в
    # файле то написание, которое попало раньше, а вновь выученное исчезло бы
    # молча).
    LISTS = ("hierarchy", "properties", "actions", "delta_properties",
             "aliases")
    # ПОРЯДОК КАНАЛОВ ПРИ СЛИЯНИИ ИЕРАРХИИ (п.A-остаток3).
    # Иерархия — НЕ список свойств: её первый элемент становится единственным
    # родителем узла (IS_A в ядре, «X — это Y» в ответе). Прежнее правило
    # «новое дописывается в хвост» значило: родом станет категория того
    # канала, который УСПЕЛ ответить первым, а того, кто ответил раньше,
    # сдвинет на вторую позицию. ЗАМЕР (реальные записи двух каналов):
    #     Вики->локалка : [0] = 'ветроуказатели'
    #     локалка->Вики : [0] = 'метеорологические приборы'
    # один и тот же флюгер, РАЗНЫЙ РОДИТЕЛЬ В ЯДРЕ.
    # Ранги взяты не из воздуха и не из CHANNEL_CONFIDENCE (он про вес синапса,
    # здесь нужен вопрос «чей ПОРЯДОК ранжирован»):
    #   user — человек называет род словами («пчела — летаемое насекомое»);
    #   llm  — иерархия ЛОКАЛКИ ранжирована: 15 из 18 цепочек заканчиваются
    #          верхним корнем «*объект*», то есть направление «от ближнего к
    #          дальнему» внутри неё есть;
    #   text — единичная категория извлечения, ранжировать нечего;
    #   wiki — категории алфавитны (14 из 22 списков строго алфавитны после
    #          отсева служебных) и в редакционный род не попали НИ РАЗУ (0/7).
    # Ранжирование по СОДЕРЖАНИЮ (граф родителей категорий) этой замены НЕ
    # заменена: оно проверено и дало 1 совпадение из 5 (pA_rank.py), то есть
    # не лучше алфавита — см. test_experience_choice_contract.
    HIERARCHY_RANK = {"user": 0, "llm": 1, "text": 2, "wiki": 3}

    def _rank(prov):
        """
        Лучший (наименьший) ранг канала в происхождении записи, None если
        метки канала нет. Записей без метки в мире большинство (текстовые,
        старые файлы) — для них прежний порядок «ранее записанное главнее»,
        иначе правка молча переставила бы половину Вселенной.
        """
        ranks = [HIERARCHY_RANK[str(p.get("source") or "").lower()]
                 for p in normalize_provenance(prov)
                 if str(p.get("source") or "").lower() in HIERARCHY_RANK]
        return min(ranks) if ranks else None

    rank_prev = _rank(merged.get("provenance"))
    rank_new = _rank(new.get("provenance"))
    # Новое становится в начало ТОЛЬКО когда его канал ранжирован лучше
    # записанного. При равных рангах (ответ модели поверх ответа модели)
    # и при неизвестных — прежнее правило: главное то, что уже лежит.
    hier_first = (rank_new is not None
                  and (rank_prev is None or rank_new < rank_prev))
    for k in LISTS:
        have = list(merged.get(k) or [])
        add = new.get(k) or []
        if not isinstance(add, list):
            add = [add]
        if k == "hierarchy" and hier_first:
            have, add = add, have
        for x in add:
            if not x:
                continue
            if x in have:
                # Позиция уже записанного НЕ меняется. Соблазн «при дубле
                # поднять категорию в начало» ЗАМЕРЕНО и убит: дублем чаще
                # всего бывает как раз верхний корень («объекты»), и он
                # переехал бы в hierarchy[0] — грубое множество стало бы родом.
                continue
            if k == "actions" and any(action_name(x).lower() == action_name(h).lower()
                                      for h in have):
                continue      # то же действие во второй форме записи
            have.append(x)
        if have:
            merged[k] = normalize_actions(have) if k == "actions" else have
    for k, v in new.items():
        if k in LISTS or k == "provenance":
            continue
        if v and not merged.get(k):
            merged[k] = v
    # ПРОИСХОЖДЕНИЕ: доказательства накапливаются, но не бесконечно — файл
    # читается человеком, и запись на 500 строк нечитабельна.
    # Обе стороны приводятся к ЕДИНОЙ схеме (п.14): иначе сравнение
    # «p not in prov» не ловило бы дубль строки и объекта об одном и том же.
    prov = normalize_provenance(merged.get("provenance"))
    for p in normalize_provenance(new.get("provenance")):
        if p not in prov:
            prov.append(p)
    if prov:
        merged["provenance"] = prov[-12:]
        # СКАЛЯР ПРОИСХОЖДЕНИЯ ДОГОНЯЕТ ПОСЛЕДНЕЕ ДОКАЗАТЕЛЬСТВО.
        # Правило «новое добавляет, но не стирает» выше распространялось и на
        # learned_from — и это была ошибка НЕ про данные. Данные обязаны
        # сохраняться; метаданные отвечают на другой вопрос («кто ПОСЛЕДНИЙ
        # раз это записал»), и «не стирать» для них значит «врать прошлоем».
        # ЗАМЕРЕНО: ответ человека поверх ответа модели давал
        # provenance=['llm','user'] при learned_from='llm'. Пять мест кода
        # читают этот скаляр (веса, порядок слияния иерархии), тестов на него
        # было ноль.
        last = str(prov[-1].get("source") or "")
        if last:
            merged["learned_from"] = last
    # ЧИСТКА ИЕРАРХИИ (см. meaningful_categories). Concept берётся из обеих
    # записей: «новое» может прийти без него.
    concept = merged.get("concept") or new.get("concept") or ""
    if merged.get("hierarchy"):
        clean = meaningful_categories(concept, merged["hierarchy"])
        if clean:
            merged["hierarchy"] = clean
        else:
            merged.pop("hierarchy", None)
    return merged
