def profile_of(verb: str) -> Optional[List[int]]:
    """Профиль действия либо None — ЕСЛИ мы его действительно знаем.

    Возвращать догадку вместо None нельзя: профиль участвует в матчинге
    предиктивного цикла, и выдуманное число молча порождает ложные
    предсказания («птица гасит огонь»), которые невозможно заметить.
    """
    prof = ACTION_PROFILES.get((verb or "").lower().strip())
    return list(prof) if isinstance(prof, list) else None


def is_known_action(verb: str) -> bool:
    return profile_of(verb) is not None


def looks_like_verb(word: str) -> bool:
    """
    Похоже ли слово на ДЕЙСТВИЕ, а не на сущность.

    Три признака, и все — про саму ЛЕГКОСТЬ распознавания, а не про словарь:
      1) в справочнике профилей (или это возвращённая форма известного
         глагола: «мнёт» -> «мять»);
      2) возвращает -ся/-сь («катиться») — такого не бывает у существительных;
      3) морфология говорит VERB или INFN. INFN обязателен: леммы глаголов в
         памяти хранятся инфинитивами («гасить», «чинить»), и без него вся
         живая память осталась бы с неверным asked_empty.

    Возвращать False при недоступной морфологии НЕЛЬЗЯ молча: тогда глагол
    снова уйдёт в очередь «неизвестных сущностей», и именно тот дефект, ради
    которого написан этот модуль, вернётся тихо.
    """
    w = (word or "").lower().strip()
    if not w:
        return False
    if w in ACTION_PROFILES:
        return True
    if w.endswith(("ся", "сь")):
        return True
    try:
        return Morph.pos(w).startswith(("VERB", "INFN"))
    except Exception:
        return False
