import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("LIPID2_STATUS", "0")

from core.extract import SimpleExtractor  # noqa: E402
from core.morph import split_clauses      # noqa: E402

_EX = SimpleExtractor()


def tripes(sentence):
    """[(head, relation, tail)] — то, чем меряют все контракты экстрактора."""
    return [(f.head, f.relation, f.tail) for f in _EX.extract(sentence).facts]


def negmap(sentence):
    return {(f.head, f.relation, f.tail): f.negated
            for f in _EX.extract(sentence).facts}


class TestSecondPredicateIsLost(unittest.TestCase):
    """САМОЕ КРАСНОЕ: второе сказуемое обязано стать связью, а не исчезнуть."""

    def test_adversative_but_yields_second_relation(self):
        """«Егор любит жену, но боится мамы» — БОЯТЬСЯ обязано быть записано."""
        t = tripes("Егор любит жену, но боится мамы.")
        self.assertIn(("егор", "CAN_DO", "бояться"), t,
                      f"второе сказуемое потеряно: {t}")
        self.assertIn(("бояться", "OBJECT_OF", "мама"), t,
                      f"объект второго сказуемого потерян: {t}")

    def test_object_does_not_leak_to_the_wrong_verb(self):
        """
        «мама» НЕ имеет права висеть на «любить». Это не косметика: связь
        любить--PART_OF-->мама читается как «мама — часть любить», и отличить
        её от настоящего знания в графе нельзя. Ложная связь дороже
        отсутствующей (правило проекта).
        """
        t = tripes("Егор любит жену, но боится мамы.")
        self.assertNotIn(("любить", "PART_OF", "мама"), t,
                         f"объект второго сказуемого прилип к первому: {t}")

    def test_conjunction_and_with_two_finite_verbs(self):
        """Запятая не при чём: «и» при двух личных глаголах — то же требование."""
        t = tripes("Егор любит жену и боится мамы.")
        self.assertIn(("егор", "CAN_DO", "бояться"), t,
                      f"«и» с вторым сказуемым потеряно: {t}")

    def test_bare_coordinate_verb_inherits_the_actor(self):
        """
        «Мальчик читал и рисовал»: у второго глагола НЕТ своего подлежащего,
        и оно обязано прийти из первой части. Именно этот замер показал, что
        одного разрезания мало.
        """
        t = tripes("Мальчик читал и рисовал.")
        self.assertIn(("мальчик", "CAN_DO", "читать"), t, f"первое пропало: {t}")
        self.assertIn(("мальчик", "CAN_DO", "рисовать"), t,
                      f"второе сказуемое осталось без актёра: {t}")

    def test_negated_second_predicate_keeps_its_own_object(self):
        """
        «Жена затаила обиду, но не показала вида»: «вида» — объект
        ВТОРОГО глагола, а не часть первого, и отрицание обязано дойти до
        самого факта, а не осядет в заметке про «?».
        """
        s = "Жена затаила обиду, но не показала вида."
        t = tripes(s)
        self.assertIn(("жена", "CAN_DO", "показать"), t,
                      f"второе сказуемое потеряно: {t}")
        self.assertNotIn(("затаить", "PART_OF", "вид"), t,
                         f"«вида» прилипло к чужому глаголу: {t}")
        self.assertTrue(negmap(s).get(("жена", "CAN_DO", "показать"), False),
                        "«НЕ показала» записано без отрицания")


class TestClauseBoundaryExists(unittest.TestCase):
    """Граница обязана появиться в морфологии, а не в догадке экстрактора."""

    def test_split_clauses_splits_on_adversative_with_finite_verb(self):
        parts = split_clauses("Егор любит жену, но боится мамы")
        self.assertEqual(len(parts), 2,
                         f"противительный союз не дал границы: {parts}")
        self.assertTrue(all(not p["sub"] for p in parts),
                        f"однородная часть помечена придаточной (ложь для «но»): "
                        f"{parts}")

    def test_split_clauses_splits_on_and_with_finite_verb(self):
        parts = split_clauses("Егор любит жену и боится мамы")
        self.assertEqual(len(parts), 2,
                         f"«и» при двух личных глаголах не дал границы: {parts}")


class TestDoNotBreakWhatIsLocked(unittest.TestCase):
    """
    ПОГРАНИЧЬЕ. Каждый кейс ниже УЖЕ заперт другими контрактами и обязан
    выйти из правки НЕИЗМЕННЫМ. Здесь собрано то, что ломается первым, если
    резать по запятой или по союзу БЕЗ проверки «за союзом финитный глагол».
    """

    def test_object_enumeration_stays_one_clause(self):
        """«ловит мышь И птицу»: после «и» существительное — резать нечего."""
        parts = split_clauses("Кошка ловит мышь и птицу")
        self.assertEqual(len(parts), 1, f"однородные объекты разъехались: {parts}")
        t = tripes("Кошка ловит мышь и птицу.")
        self.assertIn(("ловить", "OBJECT_OF", "мышь"), t)
        self.assertIn(("ловить", "OBJECT_OF", "птица"), t)

    def test_adversative_without_verb_keeps_negation_scope(self):
        """
        «Кит не рыба, а млекопитающее» — заперто test_negation_contract.
        После «а» существительное; разрез УБЬЕТ именование и оставит граф без
        млекопитающего, а отрицание потеряет пару.
        """
        parts = split_clauses("Кит не рыба, а млекопитающее")
        self.assertEqual(len(parts), 1,
                         f"именное противопоставление разрезано: {parts}")
        s = "Кит не рыба, а млекопитающее."
        t = tripes(s)
        self.assertIn(("кит", "IS_ROLE", "рыба"), t, f"отрицаемое пропало: {t}")
        self.assertIn(("кит", "IS_ROLE", "млекопитающее"), t,
                      f"утверждаемое пропало: {t}")
        nm = negmap(s)
        self.assertTrue(nm[("кит", "IS_ROLE", "рыба")], "«не рыба» перестало быть НЕ")
        self.assertFalse(nm[("кит", "IS_ROLE", "млекопитающее")],
                         "отрицание перелилось на утверждаемое")

    def test_purpose_clause_still_parsed_by_parts(self):
        """Заперто: «кошка спрятала мышь, чтобы не ловить её» (PURPOSE + НЕ)."""
        t = tripes("Кошка спрятала мышь, чтобы не ловить её.")
        self.assertIn(("кошка", "CAN_DO", "спрятать"), t)
        self.assertIn(("спрятать", "PURPOSE", "ловить"), t)
        self.assertIn(("спрятать", "OBJECT_OF", "мышь"), t)
        self.assertTrue(negmap("Кошка спрятала мышь, чтобы не ловить её.")[
                        ("спрятать", "PURPOSE", "ловить")],
                        "«не» из придаточного цели перестало отрицать ловить")

    def test_relative_clause_regression(self):
        """Заперто п.18: «Мяч, который бросил мальчик, укатился»."""
        t = tripes("Мяч, который бросил мальчик, укатился.")
        self.assertIn(("мяч", "CAN_DO", "укатиться"), t, f"главное потеряно: {t}")
        self.assertIn(("мальчик", "CAN_DO", "бросить"), t, f"придаточное потеряно: {t}")
        self.assertIn(("бросить", "OBJECT_OF", "мяч"), t)

    def test_place_clause_regression(self):
        """Заперто: «Дом, где жил пёс, сгорел»."""
        t = tripes("Дом, где жил пёс, сгорел.")
        self.assertIn(("дом", "CAN_DO", "сгореть"), t)
        self.assertIn(("жить", "LOCATED_IN", "дом"), t)
        self.assertIn(("пёс", "CAN_DO", "жить"), t)

    def test_simple_sentence_regression(self):
        """Простое предложение не обязано ничего покупать за эту правку."""
        t = tripes("Жена затаила обиду.")
        self.assertEqual(t, [("жена", "CAN_DO", "затаить"),
                             ("затаить", "OBJECT_OF", "обида")],
                         f"простое предложение изменилось: {t}")


class TestNoSilentZero(unittest.TestCase):
    """
    Молчаливый ноль — главный враг этой правки: разрезанная часть без актёра
    даёт РОВНО тот же пустой результат, что и отсутствие правки. Поэтому
    отказ обязан быть назван, а не выдан отсутствием связей.
    """

    def test_clause_without_actor_says_so(self):
        """Голая часть «боится мамы» НЕ может придумать себе субъекта."""
        sf = _EX.extract("Боится мамы.")
        self.assertEqual(sf.facts, [],
                         "субъект выдуман из косвенного падежа")
        self.assertTrue(sf.notes, "пустой разбор без единой заметки — тихий ноль")

    def test_inherited_actor_is_a_mechanism_not_a_guess(self):
        """
        Наследование актёра НЕ должно работать ТАМ, где у части свой субъект:
        «Егор любит жену, но мама боится его» — у второй части СВОЙ актёр,
        и подставлять Егора к «боится» значит переврать смысл.
        """
        t = tripes("Егор любит жену, но мама боится Егора.")
        self.assertNotIn(("егор", "CAN_DO", "бояться"), t,
                         f"актёр второй части подставлен вместо её собственного: {t}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
