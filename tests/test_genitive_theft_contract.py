#!/usr/bin/env python3
"""КОНТРАКТ ФАЗЫ 1: родительный определитель не крадёт дополнение глагола.

Замер (tools/genitive_theft.py, experiments/GENITIVE_THEFT.txt) показал:
конструкция «сущ.1 сущ.2-род.п. глагол дополнение» занимает слот дополнения
родительным определителем. Решётка 2x2 крадёт во всех четырёх клетках,
контроль без определителя не ошибается ни разу. Кража НЕ зависит ни от
одушевлённости, ни от падежа — значит признак различения не морфологический.

РЕШЕНИЕ БОССА (03.11): вариант (а), ДВЕ фазы, не одним коммитом. Фаза 1 —
ПРЕКРАТИТЬ КРАЖУ, ребро для определителя НЕ создавать. «Потеря связи —
честное незнание, кража дополнения — активная ложь; ложь хуже пропуска».

ЧТО ЗАПЕРАТО РОВНО В ТОМ ВИДЕ, КАК ЕГО ВИДИТ МОЗГ. Кража выходит из
экстрактора ДВУМЯ следами, и контракт запирает оба — иначе «починка» сотрёт
один след и оставит другой, а вывод про неё ничего нельзя будет сказать:

  1. событие: obj = определитель вместо настоящего дополнения;
  2. факты: ЛИШНЕЕ ребро «глагол OBJECT_OF определитель», лежащее РЯДОМ с
     правильным («пожаловаться RECIPIENT муж» там же, где и «OBJECT_OF егор»).

ЗАПРЕТ НА РЕБРО — тоже замок, а не отсутствие проверки. «Связь (жена, егор)
отсутствует» обязана быть видна: фаза 1 убирает ложь, она НЕ заполняет
пробел (это фаза 2, отдельный выбор отношения).

ЧЕГО ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО. Контроля «Хвост собаки мокрый» — он зелёный и
заперт test_learning_contract.py:89; в бесглагольной конструкции нет
глагольного дополнения, значит там определитель становится PART_OF ЗАКОННО.
Если после фазы 1 он покраснеет — сломан бесглагольный разбор, откат.

Замер дешёвый: SimpleExtractor без мира и без морфологического сервера,
0,15 с на предложение.

    LIPID2_STATUS=0 .venv/bin/python -m unittest tests.test_genitive_theft_contract
"""
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.extract import SimpleExtractor  # noqa: E402

_EX = SimpleExtractor()


def ev_of(sentence):
    """(субъект, действие, объект) первого события — то, что мир кладёт в
    events. Настоящее время событий не даёт, поэтому меряется прошлое."""
    evs = _EX.extract(sentence).events
    if not evs:
        return None
    return (evs[0].subject, evs[0].action, evs[0].obj)


def triples(sentence):
    return [(f.head, f.relation, f.tail) for f in _EX.extract(sentence).facts]


# Предложения, в которых кража ИЗМЕРЕНА (experiments/GENITIVE_THEFT.txt).
# opredelitel — родительный при подлежащем; dopolnenie — то, что глагол
# требует по падежу и что сегодня пропадает.
STOLEN = [
    ("Жена Егора пожаловалась мужу.", "жена", "пожаловаться", "муж", "егор"),
    ("Мать Егора позвонила сыну.", "мать", "позвонить", "сын", "егор"),
]

# Решётка 2x2: одушевлённый/неодушевлённый определитель x датив/винитель
# дополнения. Крадёт каждая клетка — поэтому ни один из признаков починкой
# быть не может.
GRID = [
    ("Жена Егора улыбнулась мужу.", "жена", "улыбнуться", "муж", "егор"),
    ("Жена Егора увидела брата.", "жена", "увидеть", "брат", "егор"),
    ("Хозяйка дома улыбнулась соседке.", "хозяйка", "улыбнуться", "соседка",
     "дом"),
    ("Хозяйка дома увидела брата.", "хозяйка", "увидеть", "брат", "дом"),
]

# Контроль: тот же глагол и то же дополнение БЕЗ родительного определителя.
# Эта проверка ЗЕЛЁНАЯ сегодня и обязана остаться зелёной: она охраняет
# базовый разбор от «починки», которая его съест.
CONTROL = [
    ("Жена пожаловалась мужу.", "жена", "пожаловаться", "муж"),
    ("Мать позвонила сыну.", "мать", "позвонить", "сын"),
    ("Хозяйка увидела брата.", "хозяйка", "увидеть", "брат"),
]

# ДОПОЛНЕНИЕ СТОИТ ДО ГЛАГОЛА («Жена Анну любила»). Слово стоит сразу за
# подлежащим, как и украденный определитель, и ОТЛИЧАЕТСЯ ТЕМ, что
# родительного у него НЕТ («Анну» — только винительный). Мутация, убравшая
# проверку родительного у самого слова, проходила ЗЕЛЁНОЙ на всём остальном
# корпусе и сжигала именно эти предложения: «Жена Анну любила» теряла
# «любить OBJECT_OF анна» совсем. Заперто здесь, потому что это тот самый
# случай, где запрет обязан ПРОМОЛЧАТЬ.
GENITIVE_FREE = [
    ("Жена Анну любила.", "жена", "любить", "анна"),
    ("Хозяйка соседку звала.", "хозяйка", "звать", "соседка"),
    # ОДНОРОДНЫЕ дополнения перед глаголом. Здесь у ПЕРВОГО объекта
    # появляется альтернатива — второй объект того же глагола, — и проверка
    # «а не определитель ли это?» срабатывает по-настоящему. Без требования
    # родительного у самого слова первый объект съедался вторым:
    # «Мать Анну и Машу кормила» теряла «кормить OBJECT_OF анна» и отдавала
    # событие Маше. Одиничное дополнение такой ловушки не даёт — второй
    # альтернативы просто нет, — поэтому эти три фразы и стоят здесь.
    ("Мать Анну и Машу кормила.", "мать", "кормить", "анна"),
    ("Хозяйка соседку и её дочь звала.", "хозяйка", "звать", "соседка"),
    ("Отец Анну и Машу встретил у ворот.", "отец", "встретить", "анна"),
]

# ГДЕ ФАЗА 1 ПЛАТИТ. Решётка кражи включает её только там, где при глаголе
# ЕСТЬ ДРУГОЙ прямой участник (OBJECT_OF или RECIPIENT) — тогда родительный
# обязан уступить ему место. Здесь альтернативы нет: единственный кандидат
# на дополнение и есть родительный.
#
# «Мать сына встретила у ворот» — родительный ОКАЗЫВАЕТСЯ ИСТИННЫМ
# дополнением (сына = вин. от «сын», порядок обратный). Снятие факта
# оставляло событие без OBJECT_OF, а _collect_events берёт obj из ПЕРВОГО
# не-CAN_DO зависимого и брал МЕСТО: событие становилось
# (мать, встретить, ВОРОТА). Это не прекращение лжи, это ЗАМЕНА правды
# ложью — по правилу «ложь хуже пропуска» так нельзя.
#
# «Крыша дома покраснела» — родительный действительно лживый объект, но
# снять его нечем: альтернативы нет, и на его место сел бы мусор. Поэтому
# СТАРАЯ ложь здесь ОСТАЁТСЯ и записана как известный дефект
# (experiments/GENITIVE_THEFT_PHASE1.txt). Новая ложь недопустима, старая —
# документирована.
NO_ALTERNATIVE = [
    ("Мать сына встретила у ворот.", "мать", "встретить", "сын"),
    ("Крыша дома покраснела.", "крыша", "покраснеть", "дом"),
    ("Ручка двери сломалась.", "ручка", "сломаться", "дверь"),
]

# ДОПОЛНЕНИЕ СТОИТ ПОСЛЕ КОСОГО СУЩЕСТВИТЕЛЬНОГО. «Витя дал кошке корм»:
# перед «корм» стоит «кошке» — существительное, но в ДАТЕЛЬНОМ, а не в
# им.падеже. Именно «им.падеж слева» отличает определитель от дополнения,
# и мутация, ослабившая это требование до «любое существительное слева»,
# проходила ЗЕЛЁНОЙ всем контрактом и съедала настоящий объект:
# «дать OBJECT_OF корм» исчезало, оставалось только «дать RECIPIENT кошка».
# У слова «корм» родительный вариант есть («корма»), поэтому его спасает
# ТОЛЬКО проверка падежа предыдущего слова.
# Обе фразы взяты не наугад: они есть в золотом корпусе (dev и held-out),
# то есть достижимость проверена на размеченном материале, а не на
# выдуманном (урок 81).
AFTER_OBLIQUE = [
    ("Витя дал кошке корм.", "дать", "корм", "витя", "дать", "корм"),
    ("Хозяйка дала соседке соли.", "дать", "соль", "хозяйка", "дать",
     "соседка"),
]


class TestTheftStoppedInEvents(unittest.TestCase):
    """Событие обязано хранить ИСТИННОЕ дополнение, а не определитель."""

    def test_dative_object_survives_genitive_modifier(self):
        for sent, subj, act, obj, thief in STOLEN:
            with self.subTest(sentence=sent):
                self.assertEqual(
                    ev_of(sent), (subj, act, obj),
                    f"{sent!r}: событие обязано хранить дополнение {obj!r}, "
                    f"а не украденный определитель {thief!r}")

    def test_thief_absent_from_event_object(self):
        """Тот же факт с другой стороны: поле obj не обязано быть вообще
        ничем из списка определителей. Первая проверка называет желаемое,
        эта называет запрет — вместе они не дают починке увести obj в
        третью строку, которая тоже не дополнение."""
        for sent, _s, _a, obj, thief in STOLEN + GRID:
            with self.subTest(sentence=sent):
                ev = ev_of(sent)
                self.assertIsNotNone(ev, f"{sent!r}: событие пропало совсем")
                self.assertNotEqual(
                    ev[2], thief,
                    f"{sent!r}: obj остался украденным определителем {thief!r}")


class TestTheftStoppedInFacts(unittest.TestCase):
    """Лишнее ребро «глагол OBJECT_OF определитель» — второй след кражи.

    Правильное дополнение в фактах лежит РЯДОМ («пожаловаться RECIPIENT
    муж»), поэтому проверка «дополнение есть» тут ничего не охраняет: она
    была зелёной и во время кражи. Охраняет только запрет лживого ребра."""

    def test_no_fact_points_at_the_genitive_modifier(self):
        for sent, _subj, act, _obj, thief in STOLEN + GRID:
            with self.subTest(sentence=sent):
                got = [(h, r, t) for h, r, t in triples(sent)
                       if h == act and t == thief]
                self.assertEqual(
                    got, [],
                    f"{sent!r}: глагол {act!r} обязан перестать указывать на "
                    f"родительный определитель {thief!r} — тот не объект "
                    f"действия")

    def test_true_object_still_present_in_facts(self):
        """Снятие лживого ребра не обязано унести настоящее. Без этой
        проверки «починка» свелась бы к удалению факта, и кража стала бы
        молчанием, а не правдой."""
        rows = [(s, a, o) for s, _su, a, o, _th in STOLEN + GRID] \
            + [(s, a, o) for s, _su, a, o in CONTROL]
        for sent, act, obj in rows:
            with self.subTest(sentence=sent):
                got = {(h, r, t) for h, r, t in triples(sent)}
                self.assertTrue(
                    any(h == act and t == obj for h, r, t in got),
                    f"{sent!r}: дополнение {obj!r} пропало из фактов — "
                    f"фаза 1 обязана прекратить кражу, а не сжечь данные")


class TestPhaseOneAddsNoKinshipEdge(unittest.TestCase):
    """Фаза 1 НЕ заводит ребро (жена, егор). Заполнять пробел — фаза 2,
    у неё отдельный выбор отношения и отдельный коммит: иначе нельзя
    различить, что починило красные — прекращение кражи или новое ребро."""

    def test_no_edge_between_head_and_modifier(self):
        for sent, subj, _act, _obj, thief in STOLEN + GRID:
            with self.subTest(sentence=sent):
                got = [(h, r, t) for h, r, t in triples(sent)
                       if {h, t} == {subj, thief}]
                self.assertEqual(
                    got, [],
                    f"{sent!r}: фаза 1 не имеет права заводить ребро "
                    f"{subj!r}—{thief!r}; это задача фазы 2")


class TestGenitiveFreeObjectSurvives(unittest.TestCase):
    """Запрет обязан промолчать там, где родительного нет вовсе.

    Порядок «подлежащее + дополнение + глагол» ставит дополнение в ту же
    позицию, что и определитель (сразу за им.падежом). Единственное, чем оно
    отличается, — отсутствие родительного варианта. Без этой проверки
    починка могла бы строиться на одном лишь соседстве слов и тихо есть
    объекты обратного порядка."""

    def test_object_before_verb_kept(self):
        for sent, subj, act, obj in GENITIVE_FREE:
            with self.subTest(sentence=sent):
                self.assertEqual(
                    ev_of(sent), (subj, act, obj),
                    f"{sent!r}: дополнение перед глаголом потеряно — запрет "
                    f"сработал там, где родительного у слова нет")

    def test_object_before_verb_present_in_facts(self):
        for sent, _subj, act, obj in GENITIVE_FREE:
            with self.subTest(sentence=sent):
                got = {(h, r, t) for h, r, t in triples(sent)}
                self.assertTrue(
                    any(h == act and t == obj for h, r, t in got),
                    f"{sent!r}: «{act} OBJECT_OF {obj}» пропало из фактов — "
                    f"фаза 1 задела порядок «объект перед глаголом»")


class TestObjectAfterObliqueNounSurvives(unittest.TestCase):
    """Слово слева в косом падеже — НЕ владелец, дополнение обязано жить.

    Класс тот же, что поймал М3: запрет стоит в позиции, где его невозможно
    отличить от настоящего дополнения одним соседством слов. Разница в том,
    ЧТО именно теряет система. Здесь теряется ПРЯМОЙ объект при уже
    имеющемся косом — то есть фаза 1 украла бы дополнение ровно там, где
    она существует для того, чтобы его защищать.
    """

    def test_direct_object_after_oblique_kept(self):
        for sent, act, obj, *_rest in AFTER_OBLIQUE:
            with self.subTest(sentence=sent):
                got = {(h, r, t) for h, r, t in triples(sent)}
                self.assertTrue(
                    any(h == act and r == "OBJECT_OF" and t == obj
                        for h, r, t in got),
                    f"{sent!r}: «{act} OBJECT_OF {obj}» пропало — запрет "
                    f"сработал после существительного в косом падеже, а там "
                    f"владельца нет")

    def test_no_note_about_modifier(self):
        """Заметка о вытеснении — часть запрета. Если её нет, факт пропал
        молча (а молчаливая потеря — это тот нуль, который нельзя отличить
        от незнания). Здесь заметки быть не должно ВООБЩЕ: запрет обязан
        молчать, а не объяснять снятие несуществующего факта."""
        for sent, *_rest in AFTER_OBLIQUE:
            with self.subTest(sentence=sent):
                notes = _EX.extract(sent).notes
                self.assertEqual(
                    [n for n in notes if "вытеснен" in n], [],
                    f"{sent!r}: запрет сработал там, где владельцевого "
                    f"им.падежа слева нет")


class TestOnlyNewLieIsRefused(unittest.TestCase):
    """СТАРАЯ ложь допустима, НОВАЯ ложь недопустима.

    Фаза 1 обязана убирать ложь, которую ОНА приносит, а не все
    предсуществующие дефекты. Если снятие родительного оставляет событие
    без OBJECT_OF, его заполнит первое косое зависимое (место, орудие,
    обстоятельство) — и система начнёт утверждать то, чего в предложении не
    было вовсе. Поэтому запрет обязан МОЛЧАТЬ там, где при глаголе нет
    другого прямого участника (OBJECT_OF или RECIPIENT)."""

    def test_no_substitute_object_from_oblique_case(self):
        """Ни одно событие не обязано получить объект из косого падежа
        из-за снятого родительного: «встретить у ворот» — это МЕСТО."""
        for sent, subj, act, obj in NO_ALTERNATIVE:
            with self.subTest(sentence=sent):
                self.assertEqual(
                    ev_of(sent), (subj, act, obj),
                    f"{sent!r}: событие обязано остаться на {obj!r}; фаза 1 "
                    f"не имеет права заменить правду местом/орудием — при "
                    f"глаголе нет другого прямого дополнения")

    def test_direct_object_survives_without_alternative(self):
        """«Мать сына встретила у ворот»: здесь родительный и ЕСТЬ объект.
        Снятие факта убило бы единственную связь события с участником."""
        sent, _subj, act, obj = NO_ALTERNATIVE[0]
        got = {(h, r, t) for h, r, t in triples(sent)}
        self.assertTrue(
            any(h == act and t == obj for h, r, t in got),
            f"{sent!r}: «{act} OBJECT_OF {obj}» пропало — запрет сработал "
            f"без альтернативы и оставил событие голодным")


class TestOldLieKeptAndNamed(unittest.TestCase):
    """СТАРАЯ ложь, оставленная намеренно, обязана быть НАЗВАНА.

    «Крыша дома покраснела» даёт событие (крыша, покраснеть, ДОМ) — это
    ложь: крыша не краснеет ОТ ДОМА, «дома» здесь родительный определитель.
    Сужение фазы 1 её НЕ убирает, потому что убирать нечем: при глаголе нет
    другого прямого участника, и на освободившийся слот сядет косое
    зависимое — новая ложь вместо старой.

    Разница с test_no_substitute_object_from_oblique_case в одном: там
    ложь НОВАЯ (её принесли мы), там запрет обязан молчать. Здесь ложь
    лежала до нас, и мы её оставляем. Оставить чужую ложь — можно, если
    она записана; внести свою — нельзя. Поэтому замок проверяет не только
    вывод, но и наличие записи в experiments/GENITIVE_THEFT_PHASE1.txt:
    без неё завтра кто-то прочитает зелёный тест как «система права»."""

    OLD_LIE = [("Крыша дома покраснела.", "крыша", "покраснеть", "дом"),
               ("Ручка двери сломалась.", "ручка", "сломаться", "дверь")]
    RECORD = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "experiments", "GENITIVE_THEFT_PHASE1.txt")

    def test_old_lie_still_present(self):
        """Замок на то, что сужение ВЕРНУЛО старую ложь, а не придумало
        новую. Если вывод изменится — изменится и этот замок, а не
        пройдёт молча."""
        for sent, subj, act, obj in self.OLD_LIE:
            with self.subTest(sentence=sent):
                self.assertEqual(
                    ev_of(sent), (subj, act, obj),
                    f"{sent!r}: ожидам ЗДЕСЬ запертую старую ложь "
                    f"(obj={obj!r}); вывод изменился — надо переписать и "
                    f"запись в experiments/GENITIVE_THEFT_PHASE1.txt")

