"""
КОНТРАКТ: ГОВОРИЛКА-КОНСТРУКТОР (кирпич №1 по плану советчиков).

ДЫРА (замеренная сегодня)
------------------------
Система умеет ПОНИМАТЬ вопросы и держать факты в базе, но НЕ умеет
собрать из ролей корректное русское предложение. Модуля генерации речи
нет вовсе: `lang/ru/` содержит только разбор (questions/lemma/text).

ЧТО ЗАКРЕПЛЕНО
--------------
Ручная ролевая структура (субъект/действие/объект/обстоятельства) ->
ОДНО грамматически корректное русское предложение. Это самый изолированный
кирпич: вход детерминирован (рукописная структура), думалка не участвует.
Реализация обязана:

1. УПРАВЛЕНИЕ ГЛАГОЛА. «освещать» требует объект в винительном падеже:
   фонарь освещал АПТЕКУ (аптека -> аптеку).
2. СОГЛАСОВАНИЕ РОДА прошедшего времени с субъектом: фонарь ОСВЕЩАЛ,
   лампа ОСВЕЩАЛА (женский род), фонари ОСВЕЩАЛИ (множественное).
3. ОБСТОЯТЕЛЬСТВО МЕСТА с предлогом: улица -> НА НОЧНОЙ УЛИЦЕ
   (прилагательное «ночной» согласуется с улицей в роде/числе/падеже).
4. СБОРКА: канонический порядок [субъект] [действие] [объект] [место] даёт
   «фонарь освещал аптеку на ночной улице» (время «ночь» растворяется в
   прилагательном обстоятельства места — как у Блока).

МУТАЦИИ, на которых контракт обязан покраснеть:
  * реализация, не склоняющая объект (вставляет лемму «аптека» вместо «аптеку»);
  * реализация, не согласующая род глагола (всегда «освещал»);
  * реализация без управления глагола (не знает, что объект — винительный);
  * реализация, не согласующая прилагательное обстоятельства
    («на ночной улице» вместо «на ночную улицу»).
"""
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from lang.ru.speaker import speaker_sentence  # noqa: E402


def frames():
    """Рукописные ролевые структуры (вход первого кирпича, без думалки)."""
    return {
        # пример 1: фонарь освещал аптеку на ночной улице
        "фонарь": {
            "predicate": "освещать",
            "subject": "фонарь",
            "object": "аптека",
            "place": "улица",
            "time": "ночь",
        },
        # женский род субъекта
        "лампа": {
            "predicate": "освещать",
            "subject": "лампа",
            "object": "аптека",
            "place": "улица",
            "time": "ночь",
        },
        # множественное число субъекта
        "фонари": {
            "predicate": "освещать",
            "subject": "фонарь",
            "subject_number": "pl",
            "object": "аптека",
            "place": "улица",
            "time": "ночь",
        },
        # без обстоятельств
        "минимум": {
            "predicate": "освещать",
            "subject": "фонарь",
            "object": "аптека",
        },
    }


class SpeakerContract(unittest.TestCase):

    def test_canonical_order_with_place_and_time(self):
        s = speaker_sentence(frames()["фонарь"])
        self.assertEqual(s, "фонарь освещал аптеку на ночной улице")

    def test_object_in_accusative(self):
        s = speaker_sentence(frames()["фонарь"])
        self.assertIn("аптеку", s)
        self.assertNotIn("аптека", s)

    def test_verb_agrees_in_gender_feminine(self):
        # лампа ОСВЕЩАЛА (женский род прошедшего времени). assertNotIn
        # здесь негоден: «освещала» СОДЕРЖИТ подстроку «освещал», поэтому
        # сверка только точным равенством различает род.
        s = speaker_sentence(frames()["лампа"])
        self.assertEqual(s, "лампа освещала аптеку на ночной улице")

    def test_verb_agrees_in_number_plural(self):
        # фонари ОСВЕЩАЛИ (множественное число)
        s = speaker_sentence(frames()["фонари"])
        self.assertIn("освещали", s)

    def test_place_adjective_agrees_in_case(self):
        s = speaker_sentence(frames()["фонарь"])
        self.assertIn("на ночной улице", s)

    def test_minimal_frame_without_circumstances(self):
        s = speaker_sentence(frames()["минимум"])
        self.assertEqual(s, "фонарь освещал аптеку")


if __name__ == "__main__":
    unittest.main()