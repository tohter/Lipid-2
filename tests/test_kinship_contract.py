    def test_wife_of_son_does_not_make_the_woman_a_son(self):
        t = tripes("Маша — жена сына Зинаиды.")
        self.assertNotIn(("маша", "IS_ROLE", "сын"), t,
                         f"Маша записана СЫНОМ (ложь): {t}")

