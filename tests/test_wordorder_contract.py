def triples(text):
    ex = SimpleExtractor()
    return {(f.head, f.relation, f.tail)
            for sf in ex.extract_text(text) for f in sf.facts}


def can_be_accusative(word):
    """Тот самый признак, на котором держится контракт (см. _can_be_accusative)."""
    return any(v["case"] == "acc"
               for v in Morph.parse_all(word)
               if v["pos"] in ("NOUN", "ADJF", "NUMR"))


class TestA1LiveDefect(unittest.TestCase):
    """Тот самый прогон витрины. Прямой порядок был верен ВСЕГДА — он и есть
    эталон: обратный порядок обязан дать ТОТ ЖЕ набор фактов."""

    def test_reversed_word_order_gives_same_facts(self):
        straight = triples("Вода гасит огонь.")
        reversed_ = triples("Огонь гасит вода.")
        self.assertIn(("вода", "CAN_DO", "гасить"), straight)
        self.assertIn(("гасить", "OBJECT_OF", "огонь"), straight)
        self.assertEqual(straight, reversed_,
                         "обратный порядок слов изменил СМЫСЛ предложения: "
                         f"прямой {sorted(straight)}, обратный {sorted(reversed_)}")

    def test_object_is_not_homonymous_genitive(self):
        """«вод» — лемма-омоним (род.п., score 0.01). Он не имел права попасть
        в граф вместо «вода»: узел с таким именем — фантом, которого ни в одном
        тексте нет. Проверяются ОБЕ позиции имени: при обратном порядке «вода»
        стоит субъектом (head), так что искать её только в tail — ошибка этого
        теста на его первой версии."""
        t = triples("Огонь гасит вода.")
        names = {n for pair in t for n in (pair[0], pair[2])}
        self.assertNotIn("вод", names,
                         f"в граф легла омонимичная лемма «вод»: {sorted(t)}")
        self.assertIn("вода", names, f"«вода» вообще пропала из разбора: {sorted(t)}")

    def test_morpha_does_not_offer_accusative_for_voda(self):
        """Замок на УТОЧНЕНИЕ постановки. Очередь утверждала, что parse_all
        даёт «вода/acc». Замер: не даёт. Если pymorphy3 когда-нибудь начнёт
        давать — этот тест сообщит, что лексикографические цифры поменялись и
        замеры пора переснимать (а не молча починит то, что не ломалось)."""
        cases = {v["case"] for v in Morph.parse_all("вода") if v["pos"] == "NOUN"}
        self.assertNotIn("acc", cases,
                         "pymorphy3 стал выдавать вин.п. у «вода» — постановка "
                         "п.A1 устарела, замеры раздела надо переснять")
        self.assertIn("nom", cases)


class TestInversionContract(unittest.TestCase):
    """Класс целиком, а не одна фраза: правка чинит класс дефектов, и замок
    обязан покрыть класс. Для каждой пары — ОДИН ожидаемый набор фактов."""

    SCENES = [
        # (прямой порядок, обратный, ожидаемый субъект, действие, объект)
        ("Вода гасит огонь.", "Огонь гасит вода.", "вода", "гасить", "огонь"),
        ("Ветер тушит свечу.", "Свечу тушит ветер.", "ветер", "тушить", "свеча"),
        ("Кошка пьёт воду.", "Воду пьёт кошка.", "кошка", "пить", "вода"),
        ("Гроза пугает кошку.", "Кошку пугает гроза.", "гроза", "пугать", "кошка"),
        ("Мальчик читает книгу.", "Книгу читает мальчик.",
         "мальчик", "читать", "книга"),
        ("Инженер проверил чертёж.", "Чертёж проверил инженер.",
         "инженер", "проверить", "чертёж"),
        # Два провала, которых в очереди НЕ БЫЛО (замер 24.10: 11/14, не 13/14).
        # Объект одушевлён/неодушевлён — неважно: агент терялся целиком.
        ("Мальчик бросил мяч.", "Мяч бросил мальчик.", "мальчик", "бросить", "мяч"),
    ]

    def test_both_orders_agree(self):
        for straight, reversed_, subj, act, obj in self.SCENES:
            with self.subTest(обратный=reversed_):
                self.assertEqual(triples(straight), triples(reversed_),
                                 f"«{reversed_}» прочитано НЕ так же, как "
                                 f"«{straight}»")

    def test_agent_and_object_roles(self):
        for straight, reversed_, subj, act, obj in self.SCENES:
            for text in (straight, reversed_):
                with self.subTest(предложение=text):
                    t = triples(text)
                    self.assertIn((subj, "CAN_DO", act), t,
                                  f"актёр «{subj}» потерян: {sorted(t)}")
                    self.assertIn((act, "OBJECT_OF", obj), t,
                                  f"объект «{obj}» потерян: {sorted(t)}")
                    # ИНВЕРСИЯ агент/объект — опаснейший класс (см. шапку):
                    self.assertNotIn((obj, "CAN_DO", act), t,
                                     f"объект «{obj}» записан АКТОРом: {sorted(t)}")


class TestRuleIsGuarded(unittest.TestCase):
    """Правило обязано молчать там, где морфология не свидетель."""

    def test_nominal_sentence_keeps_position(self):
        """В именном предложении винительного нет в природе. Здесь решает
        позиция, а не «обязательный им.п.» — иначе «Кит не рыба, а
        млекопитающее» теряет субъекта (замерено: три теста
        test_negation_contract падали, пока guard не добавили)."""
        t = triples("Кит не рыба, а млекопитающее.")
        self.assertIn(("кит", "IS_ROLE", "млекопитающее"), t)
        self.assertNotIn(("рыба", "IS_ROLE", "кит"), t,
                         "род и вид поменялись местами")

    def test_both_candidates_accusative_falls_back_to_position(self):
        """Если оба кандидата МОГУТ быть винительными, морфология молчит, и
        право выбора остаётся у позиции — ближайший перед сказуемым. Правило
        обязано молчать, а не угадывать."""
        self.assertTrue(can_be_accusative("дом"))
        self.assertTrue(can_be_accusative("мяч"))
        t = triples("Дом охранял пёс.")
        # «пёс» не может быть винительным — правило имеет право сработать;
        # проверяем именно это, потому что оно и даёт верный ответ:
        self.assertIn(("пёс", "CAN_DO", "охранять"), t)

    def test_suspicious_subject_note_survives(self):
        """Когда морфология не различает («мальчик читает книга» — оба им.-
        только) и позиция тоже не при чём, заметка о спорном субъекте обязана
        остаться ВИДНОЙ: тихая деградация = баг."""
        sf = SimpleExtractor().extract("Мальчик читает книга.")
        self.assertTrue(any("субъект спорный" in n for n in sf.notes),
                        f"сомнение спрятано, notes={sf.notes}")


