sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.extract import SimpleExtractor  # noqa: E402

_EX = SimpleExtractor()


def triples(sentence):
    return [(f.head, f.relation, f.tail) for f in _EX.extract(sentence).facts]


def facts_of(sentence):
    return _EX.extract(sentence).facts


# ОДУШЕВЛЁННЫЕ ОПРЕДЕЛИТЕЛИ ПРИ ПОДЛЕЖАЩЕМ. Это те случаи, ради которых
# затевалась фаза 2: без ребра между людьми звено 4 меряет не вывод, а пустоту.
# Отношение заперто PART_OF по решению В1; глосса неверна и названа в шапке.
PEOPLE = [
    ("Жена Егора пожаловалась мужу.", ("жена", "PART_OF", "егор")),
    ("Мать Егора позвонила сыну.", ("мать", "PART_OF", "егор")),
    ("Жена Егора улыбнулась мужу.", ("жена", "PART_OF", "егор")),
    ("Жена Егора увидела брата.", ("жена", "PART_OF", "егор")),
    ("Сестра Анны принесла воды.", ("сестра", "PART_OF", "анна")),
]

# КОНТРОЛИ. Бесглагольная конструкция пишет PART_OF именной веткой и заперта
# test_learning_contract.py:89. Фаза 2 живёт в режиме действия и не имеет
# права ни добавить туда ребро, ни убрать его. Вторая контроль — глагольная,
# одушевлённого определителя в ней нет: «ножку стола» владение проходит ДРУГОЙ
# веткой (цепочкой существительных, была в коде до фазы 2). Обе контроли
# требованы боссом (В3): «минимум две контрольные неодушевлённые, чтобы
# убедиться, что фаза 2 не трогает «хвост собаки»» — раньше в файле стояла
# ОДНА, это было невыполненное требование, а не мелочь.
CONTROLS = [
    ("Хвост собаки мокрый.", ("хвост", "PART_OF", "собака")),
    ("Хозяин сломал ножку стола.", ("ножка", "PART_OF", "стол")),
]

# ЗОНА БЕЗ АЛЬТЕРНАТИВЫ. «Крыша дома покраснела»: при глаголе нет другого
# прямого участника, guard фазы 1 НЕ срабатывает, значит и ветка фазы 2 не
# срабатывает. Ребро «крыша PART_OF дом» (оно лежит в expect h06) НЕ
# появляется, а старая ложь «покраснеть OBJECT_OF дом» остаётся. Это граница,
# а не недосмотр: снятие единственного кандидата — та самая замена правды
# ложью. Заодно это опровергает ожидание, что фазу 2 закроет h06/h11: их
# закрывает только починка «событийного объектного голода», а она отложена.
NO_RIVAL = "Крыша дома покраснела."

# ВТОРАЯ ЗОНА, КОТОРУЮ БОСС ВЕЛЕЛА НЕ ТРОГАТЬ. «Зинаида гостит в семье своего
# сына Егора»: слева от «сына» стоит «семье» С ПРЕЛОГОМ, поэтому guard фазы 1
# эту зону не видит (modifier_of_preceding возвращает False). Замер сегодня:
# гостить OBJECT_OF сын и гостить OBJECT_OF егор — оба лишних, ребро
# (сын, егор) не заводится. Дыра названа, починка — НЕ фаза 2.
OBLIQUE_ZONE = "Зинаида гостит в семье своего сына Егора."


class TestEdgeAppears(unittest.TestCase):
    """ЯДРО. Определитель при подлежащем оставляет ребро PART_OF."""

    def test_person_modifier_creates_edge(self):
        for sentence, want in PEOPLE:
            with self.subTest(sentence=sentence):
                self.assertIn(want, triples(sentence),
                              "%s: ребра %s нет; вывод: %s"
                              % (sentence, want, triples(sentence)))

    def test_edge_points_from_modified_to_modifier(self):
        """Направление не произвольно: определяется СЛОВО, стоящее слева
        («жена» зависит от «Егора», а не наоборот). Ребро «егор PART_OF жена»
        было бы обратной стрелкой, и обход пошёл бы не туда."""
        for sentence, (head, rel, tail) in PEOPLE:
            with self.subTest(sentence=sentence):
                self.assertNotIn((tail, rel, head), triples(sentence),
                                 "%s: ребро развернуто" % sentence)


class TestControlsUntouched(unittest.TestCase):
    """Контроли не имели права сдвинуться: без них любой рост рёбер зелёный."""

    def test_inanimate_modifier_still_part_of(self):
        for sentence, want in CONTROLS:
            with self.subTest(sentence=sentence):
                self.assertIn(want, triples(sentence),
                              "%s: контроль %s потерян; вывод: %s"
                              % (sentence, want, triples(sentence)))

    def test_object_of_verb_survives_edge(self):
        """Ребро определителя не имеет права вытеснить дополнение: тогда
        фаза 2 вернула бы ровно ту кражу, которую фаза 1 прекратила."""
        for sentence, _want in PEOPLE:
            with self.subTest(sentence=sentence):
                got = triples(sentence)
                verbs = [f.tail for f in _EX.extract(sentence).facts
                         if f.relation == "CAN_DO"]
                direct = [t for (h, r, t) in got if r in ("OBJECT_OF",
                                                          "RECIPIENT")]
                self.assertTrue(direct,
                                "%s: при глаголе %s не осталось ни одного "
                                "прямого участника: %s" % (sentence, verbs, got))

    def test_nominal_branch_untouched(self):
        """Именная ветка пишет PART_OF своим механизмом. Замерено ДО фазы 2 и
        заперто test_learning_contract.py:89; здесь сверяется, что новая ветка
        не ударила по чужому режиму."""
        got = triples("Маша — жена сына Зинаиды.")
        self.assertIn(("жена", "PART_OF", "сын"), got)
        self.assertIn(("сын", "PART_OF", "зинаида"), got)
        self.assertIn(("маша", "IS_ROLE", "жена"), got)


