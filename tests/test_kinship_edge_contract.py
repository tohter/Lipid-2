class TestKinshipEdgeSurvivesPastTense(unittest.TestCase):
    """«СТАТИКА ТОНЕТ В СОБЫТИИ» — ЗАПЕРЕНА. Найдено ПОСЛЕ ответа боссы
    (её В1–В4 этого не касались): в прошедшем времени `_collect_events`
    перекрашивает ВСЕ факты предложения в `predicate="event"`, а
    `brain/learner.py:1104` (`_apply_fact`) любые `is_event` выбрасывает. Итог
    по рассказу был 0 из 7 пар ПУТИ даже при живом экстракторе: ребро
    «жена PART_OF егор» в рассказе рождается РОВНО ОДНО и стоит в прошедшем
    времени («Жена Егора пожаловалась мужу…»), то есть глохнет в мире.

    ПОЧИНКА: `PART_OF` не бывает происшествием. «Жена Егора» — отношение,
    а не событие; время сказуемого не решает, чья жена. Прошедшее время
    «Жена Егора улыбнулась мужу» не превращает брак в событие.

    ГРАНИЦА ПОЧИНКИ ИЗМЕРЕНА, а не выбрана на глаз: снято из перекраски
    ТОЛЬКО `PART_OF`. Остальные отношения перекрашиваются как раньше, и это
    заперто `test_event_facts_still_marked`: без этой проверки починка
    выглядела бы «выключением событий вообще», а это ровно тот слив статики с
    динамикой, из-за которого события и вынесли в отдельную секцию
    (EVENTS_TASK.md).

    ЧТО ОСТАЛОСЬ ДЫРОЙ: 6 пар из 7 по-прежнему НЕТ ПУТИ — ни одно другое
    именное утверждение о людях рассказ не содержит. Рассказ даёт 1 из 7, и
    цифра записана как есть, а не выдана за закрытие задачи.
    """

    PAST = ["Жена Егора пожаловалась мужу.",
            "Мать Егора позвонила сыну.",
            "Сестра Анны принесла воды."]

    def test_edge_is_static_in_past_tense(self):
        for sentence in self.PAST:
            with self.subTest(sentence=sentence):
                ev = [f for f in _EX.extract(sentence).facts
                      if f.relation == "PART_OF"]
                self.assertTrue(ev, "%s: ребра нет вовсе" % sentence)
                bad = [f.key() for f in ev if f.predicate != "fact"]
                self.assertEqual(bad, [],
                                 "%s: статика помечена событием и не дойдёт "
                                 "до мира (learner её выбросит): %s"
                                 % (sentence, bad))

    def test_event_facts_still_marked(self):
        """Починка НЕ имеет права обнулить пометку событий: иначе прошлое
        снова осядет как вечное знание о виде."""
        for sentence in self.PAST:
            with self.subTest(sentence=sentence):
                facts = _EX.extract(sentence).facts
                marked = [f for f in facts if f.predicate == "event"]
                self.assertTrue(marked,
                                "%s: ни один факт не помечен событием — "
                                "прошедшее время перестало быть динамикой"
                                % sentence)
                self.assertTrue(all(f.relation != "PART_OF"
                                    for f in marked),
                                "%s: PART_OF всё-таки перекрашивается"
                                % sentence)

    def test_present_tense_edge_is_static_too(self):
        """Настоящее время и так было статикой; проверка не новая починка, а
        страховка от «починили прошедшее, сломали настоящее»."""
        ev = [f for f in _EX.extract("Жена Егора поливает цветы.").facts
              if f.relation == "PART_OF"]
        self.assertTrue(ev)
        self.assertTrue(all(f.predicate == "fact" for f in ev))


class TestGenitiveChainZoneLeftAlone(unittest.TestCase):
    """ТРЕТЬЯ ЗОНА, НАЙДЕНА ЗАМЕРОМ ПРИ ПРОБАХ, И НЕ ПОЧИНЕНА.

    «Мальчик разбил окно соседского дома.» даёт РОВНО ту же ложь, что и
    закрытая фаза 1 — лишний объект действия:
        разбить OBJECT_OF окно  (верно)
        разбить OBJECT_OF дом   (ЛОЖЬ: разбили окно, а не дом)
    и заметки guard'а при этом НЕТ (замер: notes = []).

    ПРИЧИНА ИЗМЕРЕНА, а не угадана. Guard фазы 1 требует, чтобы слева стояло
    слово В ИМЕНИТЕЛЬНОМ падеже. Здесь слева «соседского» — родительное
    прилагательное, условие не выполняется, и ветка молчит. То есть дыра не
    «забытая», а ограниченная тем же признаком, который спас дополнение в
    «Витя дал кошке корм»: ослабить его нельзя (мутация М4, 5 падений).

    РАДИУС ЗАМЕРЕН пробами, а не оценён: та же ложь в «Читательница вернула
    книгу библиотеки» (вернуть OBJECT_OF книга + вернуть OBJECT_OF библиотека,
    заметок нет). А вот «Отец похвалил сына старшего» и «Хозяйка гладила
    кошку спящую» чисты — значит зона именно «рожд.пад. при рожд.пад.», а не
    «любой согласуемый определитель».

    ПОЧЕМУ НЕ ЧИНТСЯ ЗДЕСЬ. Это второй модуль-правка внутри одной функции и
    ВНЕ решения В2 (босс писала про косой падеж с предлогом, здесь падеж не
    косой с предлогом, а цепочка согласованных родительных). Расширять
    признак «им.пад. слева» на «или род.пад. прилагательное» без замера
    радиуса — значит угадывать. Дыра названа, пробы заперты как ДЫРА, починка
    требует отдельного решения.

    ЗАПЕЧАТАНО КАК ЛОЖЬ, а не как правда: проверка требует наличия ложного
    факта, чтобы его исчезновение без замены не прошло незаметно (тот же
    приём, что TestOldLieKeptAndNamed фазы 1).
    """

    CHAIN = ["Мальчик разбил окно соседского дома.",
             "Читательница вернула книгу библиотеки."]
    CLEAN = ["Отец похвалил сына старшего.",
             "Хозяйка гладила кошку спящую."]

    def test_chain_zone_lie_is_still_produced(self):
        for sentence in self.CHAIN:
            with self.subTest(sentence=sentence):
                got = triples(sentence)
                lying = [t for (h, r, t) in got if r == "OBJECT_OF"][1:]
                self.assertTrue(lying,
                                "%s: лишнего OBJECT_OF нет — значит зону "
                                "починили НЕ этим коммитом, и надо снять "
                                "этот замок вместе с записью дыры: %s"
                                % (sentence, got))

    def test_chain_zone_makes_no_edge(self):
        """Опаснее лжи — ребро, заведенное в этой зоне молча: PART_OF здесь
        не появляется, и это граница фазы 2, а не недосмотр."""
        for sentence in self.CHAIN:
            with self.subTest(sentence=sentence):
                got = triples(sentence)
                self.assertEqual([t for (h, r, t) in got if r == "PART_OF"],
                                 [],
                                 "%s: фаза 2 залезла в третью зону: %s"
                                 % (sentence, got))

    def test_agreeing_adjective_after_object_is_clean(self):
        """Граница зоны отмерена ОТРИЦАТЕЛЬНЫМИ пробами: если бы они стали
        грязными, «цепочка родительных» оказалась бы просто «согласование»,
        и радиус дыры был бы больше заявленного."""
        for sentence in self.CLEAN:
            with self.subTest(sentence=sentence):
                got = triples(sentence)
                self.assertEqual([t for (h, r, t) in got if r == "PART_OF"],
                                 [], "%s: лишний PART_OF: %s" % (sentence, got))

    def test_third_hole_is_written_down(self):
        path = os.path.join(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__))),
            "experiments", "GENITIVE_THEFT_PHASE2.txt")
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        self.assertIn("ЦЕПОЧКА РОДИТЕЛЬНЫХ", text,
                      "третья дыра не названа в файле замера")


