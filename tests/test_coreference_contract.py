"""
КОНТРАКТ: МЕСТОИМЕНИЕ-АКТОР И ЕГО АНТЕЦЕДЕНТ (П3б).

ЗАМЕР ДО ПРАВОК (снят ДО первой строчки правки, продублирован в
experiments/P3B_BEFORE.txt; LIPID2_STATUS=0, Учитель ВЫКЛЮЧЕН — без LLM):

  «Зинаида гостит в семье сына.»  -> зинаида CAN_DO гостить,
                                      гостить LOCATED_IN семья,
                                      гостить OBJECT OF сын
  «Она недолюбливает невестку.»   -> НОЛЬ фактов,
                                      note «нет ни подлежащего (ИМ.п.),
                                      ни сказуемого»
  ВМЕСТЕ (тот же текст двумя предложениями) — то же самое: второе предложение
  не даёт НИЧЕГО. Глагол «недолюбливать» и «невестка» в мир не попадают.

  «Егор любит жену.»  -> егор CAN_DO любить, любить OBJECT OF жена
  «Он боится мамы.»   -> НОЛЬ фактов

СОСТОЯНИЯ МЕЖДУ ПРЕДЛОЖЕНИЯМИ НЕТ ВООБЩЕ. У SimpleExtractor ровно одно поле
(known — список известных слов), и оно про СЛОВА, а не про кто есть кто.
Так что это НЕ «разрешение анафоры работает плохо» — его нет. Дыра П3б шире
П3а: там сказуемое терялось внутри предложения, здесь теряется СВЯЗЬ МЕЖДУ
предложениями, то есть весь рассказ после первого предложения.

ЧТО ЗНАЧИТ «РАЗРЕШИТЬ» И ЗДЕСЬ ГРАНИЦА ПРАВИЛА
  Антецедентом признаётся существительное в ИМ.П. ПРЕДЫДУЩЕГО предложения,
  согласованное с местоимением в РОДЕ и ЧИСЛЕ. Замер признака: у «Она»
  gender='f' number='sg', у «Зинаида» g='f' n='sg', у «семья» стоит в
  предложном падеже и кандидатом НЕ является — поэтому «Она» после
  «Зинаида гостит в семье сына» обязано дать ЗИНАИДУ, а не СЕМЬЮ.

  РОД НУЖЕН ИМЕННО У МЕСТОИМЕНИЯ. У глагола настоящего времени род пуст
  («боится» g=''), так что по сказуемому род не восстановить (замер).
  Согласование по числу ловит «Они спят» / «Дети бегают» (pl).

ЧЕГО ЭТИ ТЕСТЫ НЕ ТРЕБУЮТ (границы, а не недоработки)
  НЕ ТРЕБУЮТ разрешать местоимение в последовательности предложений с другим
  субъектом в середине («Маша увидела Люду. Она…» — двусмысленно без мира).
  НЕ ТРЕБУЮТ pro-drop («Боится мамы.» без местоимения): местоимение в тексте
  ЕСТЬ, оно и есть признак; предложение без подлежащего и без местоимения
  остаётся без актёра — для него замера нет.
  НЕ ТРЕБУЮТ винительного как кандидата: в «Егор любит жену. Она плакала»
  «жена» стоит в вин.п., и подставить её значило бы решить, что объект
  действия — субъект следующего. Это отказ, и он обязан быть назван.
"""
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("LIPID2_STATUS", "0")

from core.extract import SimpleExtractor  # noqa: E402

_EX = SimpleExtractor()


def tripes(text):
    """Все связи рассказа: [(head, relation, tail)] — без LLM."""
    out = []
    for sf in _EX.extract_text(text):
        out.extend((f.head, f.relation, f.tail) for f in sf.facts)
    return out


def notes(text):
    out = []
    for sf in _EX.extract_text(text):
        out.extend(sf.notes)
    return out


class TestPronounActorIsResolved(unittest.TestCase):
    """САМОЕ КРАСНОЕ: действие с местоимением-актором обязано иметь субъекта."""

    def test_pronoun_gets_antecedent_from_previous_sentence(self):
        t = tripes("Зинаида гостит в семье сына. Она недолюбливает невестку.")
        self.assertIn(("зинаида", "CAN_DO", "недолюбливать"), t,
                      f"местоимение не разрешено, действие потеряно: {t}")
        self.assertIn(("недолюбливать", "OBJECT_OF", "невестка"), t,
                      f"объект потерялся вместе с субъектом: {t}")

    def test_masculine_pronoun(self):
        t = tripes("Егор любит жену. Он боится мамы.")
        self.assertIn(("егор", "CAN_DO", "бояться"), t, f"«он» не разрешён: {t}")
        self.assertIn(("бояться", "OBJECT_OF", "мама"), t,
                      f"объект потерян: {t}")

    def test_antecedent_is_the_subject_not_an_object_in_oblique_case(self):
        """
        «Она» обязана достаться ЗИНАИДЕ, а не СЕМЬЕ: семья стоит в предложном
        падеже («в семье»). Если бы кандидатом считалось любое существительное
        предыдущего предложения, местоимение уехало бы на место действия и
        записало бы, что СЕМЬЯ кого-то недолюбливает.
        """
        t = tripes("Зинаида гостит в семье сына. Она недолюбливает невестку.")
        self.assertNotIn(("семья", "CAN_DO", "недолюбливать"), t,
                         f"антецедентом стало обстоятельство места: {t}")

    def test_number_agreement(self):
        """«Они» согласуется с множественным числом, единственное не подходит."""
        t = tripes("Дети бегают. Они не плавают.")
        self.assertIn(("ребёнок", "CAN_DO", "плавать"), t,
                      f"«они» не разрешено во множественное: {t}")

    def test_chain_of_pronouns_does_not_reach_the_first_actor(self):
        """
        Цепочка «Зинаида … Она … Она» обязана сохраняться: второе
        местоимение получает тот же антецедент, что и первое, иначе из
        рассказа выпадает всё после второго предложения.
        """
        t = tripes("Зинаида гостит у сына. Она недолюбливает невестку. "
                   "Она постоянно придирается.")
        self.assertIn(("зинаида", "CAN_DO", "недолюбливать"), t, f"1-е: {t}")
        self.assertIn(("зинаида", "CAN_DO", "придираться"), t, f"2-е: {t}")


    def test_resolved_pronoun_reaches_the_coordinated_part(self):
        """
        ЦЕПОЧКА ДВУХ МЕХАНИЗМОВ. «Она недолюбливает невестку и постоянно
        придирается»: первая часть получает актёра из антецедента (П3б),
        вторая — из первой (П3а). Замерено между правками: вторая часть
        давала НОЛЬ с заметкой «нет ни подлежащего, ни сказуемого», потому
        что актёр первой части жил НЕ в её токенах (он пришёл из соседнего
        предложения), и поиск «своего» токена его не находил.
        """
        t = tripes("Зинаида гостит у сына. Она недолюбливает невестку "
                   "и постоянно придирается.")
        self.assertIn(("зинаида", "CAN_DO", "недолюбливать"), t, f"1-я: {t}")
        self.assertIn(("зинаида", "CAN_DO", "придираться"), t,
                      f"разрешённое местоимение не дошло до однородной части: {t}")


class TestRefusalIsHonest(unittest.TestCase):
    """
    Ложная связь дороже отсутствующей. Там, где род не сходится, связь
    обязана НЕ появиться, а отказ обязан быть назван.
    """

    def test_gender_mismatch_refuses(self):
        """«Она» при единственном кандидате мужского рода («Егор»)."""
        t = tripes("Егор любит жену. Она плакала.")
        self.assertNotIn(("егор", "CAN_DO", "плакать"), t,
                         f"род не проверен: женское местоимение получило "
                         f"мужского антецедента: {t}")
        self.assertTrue(any("местоимение" in n for n in notes(
            "Егор любит жену. Она плакала.")),
            "отказ не назван: пустой разбор неотличим от «нечего брать»")

    def test_no_antecedent_at_all_refuses(self):
        """Первое предложение рассказа не имеет предшественника."""
        sf = _EX.extract("Он боится мамы.")
        self.assertEqual(sf.facts, [], f"актёр выдуман: {sf.facts}")
        self.assertTrue(sf.notes, "пустой разбор без единой заметки")

    def test_accusative_is_not_an_antecedent(self):
        """
        «Жена» в «Егор любит жену» стоит в винительном. Сделать её субъектом
        следующего предложения — значит перепутать того, кто действует, с тем,
        на кого действует (самый дорогой класс ошибки в этом проекте).
        """
        t = tripes("Егор любит жену. Об этом она молчит.")
        self.assertNotIn(("жена", "CAN_DO", "молчать"), t,
                         f"винительный стал антецедентом: {t}")


class TestDoNotBreakWhatIsLocked(unittest.TestCase):
    """П3а и простые предложения обязаны выйти из правки неизменными."""

    def test_coordination_still_works(self):
        t = tripes("Егор любит жену, но боится мамы.")
        self.assertIn(("егор", "CAN_DO", "бояться"), t)
        self.assertIn(("бояться", "OBJECT_OF", "мама"), t)

    def test_pronoun_inside_coordinated_sentence_is_not_invented(self):
        """
        «…но она боится мамы»: у «она» нет кандидата в ИМ.П. («жена» в вин.),
        и Егор сюда подставлен быть не может. Проверено ДО правки: эта часть
        давала бояться--OBJECT_OF-->мама БЕЗ субъекта.
        """
        t = tripes("Егор любит жену, но она боится мамы.")
        self.assertNotIn(("егор", "CAN_DO", "бояться"), t,
                         f"актёр подставлен через запятую: {t}")

    def test_homonymous_verb_is_not_a_noun(self):
        """
        ОТДЕЛЬНАЯ НАХОДКА, зафиксирована чтобы не потерять, а не чтобы
        починить здесь. Замер: «Она мыла пол» -> мыло--OBJECT_OF-->пол
        (conf 0.38), «Он мыл пол» -> пол--PART_OF-->мыло (conf 0.52).
        Морфология ставит существительное «мыло» (gen 0.43) ВЫШЕ глагола
        «мыть» прош. вр. — сказуемое не находится вообще. Это ложная связь,
        и она стоит ДО всякой анафоры: сначала нужно перестать видеть
        существительное там, где глагол. Сейчас проверка фиксирует только
        одно: правка анафоры не должна ухудшить положение.
        """
        t = tripes("Она мыла пол.")
        self.assertNotIn(("она", "CAN_DO", "мыть"), t,
                         "здесь замера «умеет» нет, выдуманная связь не нужна")

    def test_simple_sentence_unchanged(self):
        self.assertEqual(tripes("Жена затаила обиду."),
                         [("жена", "CAN_DO", "затаить"),
                          ("затаить", "OBJECT_OF", "обида")])

    def test_two_independent_sentences_keep_their_own_actors(self):
        """
        «Мальчик читал. Девочка рисовала.» — у второго СВОЙ субъект, и
        подсказка из первого не имеет права его испортить.
        """
        t = tripes("Мальчик читал. Девочка рисовала.")
        self.assertIn(("мальчик", "CAN_DO", "читать"), t)
        self.assertIn(("девочка", "CAN_DO", "рисовать"), t)
        self.assertNotIn(("мальчик", "CAN_DO", "рисовать"), t,
                         f"чужой актёр подставлен туда, где свой: {t}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
