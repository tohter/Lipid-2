#!/usr/bin/env python3
"""КОНТРАКТ: «у X Y» без глагола — указатель близости, движок решает тип.

РЕШЕНИЕ ХОЗЯИНА: «у» — не владение, а ВЕЖЛИВЫЙ ПРИКАЗ движку создать связь
между правой и левой частью. «Я у сестры» = я в её жилище, рядом с ней.
Тип связи (часть / объект / пространственная близость / свойство) выбирает
ДВИЖОК по полям сущности, а не хозяин.

ГЛАВНЫЙ ПРИНЦИП НАПРАВЛЕНИЯ (хозяин): ПРАВАЯ часть относится к ЛЕВОЙ, не
наоборот. «У сестры дом» -> дом принадлежит сестре; «у дома машина» -> машина
рядом с домом. Ориентируемся по падежам: «у»+род.п. (левое) — точка привязки,
им.п. (правое) — то, что к ней относится.

ПРИОРИТЕТ ТИПА (проверен прототипом /tmp/u_proto5.py, 18/18):
  1. правое — ЧАСТЬ (зуб/хвост/колесо/крыша/клюв/ус/грива/лапа/нога/рука) -> PART_OF;
  2. левое — МЕСТО-ориентир (дом/ворота/река/стол/окно/город/море) -> LOCATED_IN;
  3. правое — СВОЙСТВО/состояние (вкус/настроение/температура/желание) -> HAS_PROPERTY;
  4. иначе правое — ВЕЩЬ (дом/локалка/кошелёк/книга/машина) -> OBJECT_OF.

НАПРАВЛЕНИЕ РЕБРА: правое -> левое. («у сестры дом» -> дом -> сестра).

ГРАНИЦА (закон «ложная связь хуже отсутствующей»): если слово движку
НЕЗНАКОМО (нет поля сущности) — честный отказ, ребро НЕ выдумывается.

ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО: «у X есть Y» (бытийное слово) — отдельный кирпич, он
заперт test_fact_fate_contract.py (possession-ветка, дыра №4). Местоимения
(«у меня», «я у сестры») — отдельная гора, связываются с антецедентом позже.

Знание о сущностях передаётся снаружи через set_entity_kind (как set_known):
эксперимент наполняет таблицы вручную, Учителя подрессируем позже.
"""
