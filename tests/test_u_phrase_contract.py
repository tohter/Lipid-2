_EX = mk()


def triples(sentence):
    return [(f.head, f.relation, f.tail) for f in _EX.extract(sentence).facts]


class TestUPhrasePart(unittest.TestCase):
    """1. правое — часть тела/механизма -> PART_OF."""

    def test_body_parts(self):
        cases = {
            "у кошки хвост": ("хвост", "PART_OF", "кошка"),
            "у птицы клюв": ("клюв", "PART_OF", "птица"),
            "у крокодила зубы": ("зуб", "PART_OF", "крокодил"),
            "у кота усы": ("ус", "PART_OF", "кот"),
            "у лошади грива": ("грива", "PART_OF", "лошадь"),
            "у зайца лапы": ("лапа", "PART_OF", "заяц"),
        }
        for sent, expected in cases.items():
            got = triples(sent)
            self.assertIn(expected, got,
                          "%r: жду %s, есть %s" % (sent, expected, got))

    def test_mechanical_parts(self):
        for sent, expected in {
            "у машины колесо": ("колесо", "PART_OF", "машина"),
            "у дома крыша": ("крыша", "PART_OF", "дом"),
            "у двери ручка": ("ручка", "PART_OF", "дверь"),
        }.items():
            got = triples(sent)
            self.assertIn(expected, got,
                          "%r: жду %s, есть %s" % (sent, expected, got))


