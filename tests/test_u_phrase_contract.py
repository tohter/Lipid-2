class TestUPhraseState(unittest.TestCase):
    """4. правое — свойство/состояние -> HAS_PROPERTY."""

    def test_state(self):
        cases = {
            "у Аманды талант": ("талант", "HAS_PROPERTY", "аманда"),
            "у крокодила желание": ("желание", "HAS_PROPERTY", "крокодил"),
            "у кошки чутьё": ("чутьё", "HAS_PROPERTY", "кошка"),
        }
        for sent, expected in cases.items():
            got = triples(sent)
            self.assertIn(expected, got,
                          "%r: жду %s, есть %s" % (sent, expected, got))

    def test_state_with_adjective(self):
        """Прилагательное привязывается к правому, а не ломает «у»-связь."""
        sent = "у Аманды хороший вкус"
        got = triples(sent)
        self.assertIn(("вкус", "HAS_PROPERTY", "аманда"), got,
                      "%r: владелец вкуса потерян, есть %s" % (sent, got))
        self.assertIn(("вкус", "HAS_PROPERTY", "хороший"), got,
                      "%r: прилагательное не привязано, есть %s" % (sent, got))
        # «вкус у Аманды» НЕ близость: ребро LOCATED_IN(вкус, аманда) ложно.
        self.assertNotIn(("вкус", "LOCATED_IN", "аманда"), got,
                         "%r: вкус не может быть ЛЕЖАТЬ у Аманды: %s"
                         % (sent, got))


class TestUPhraseHonestRefusal(unittest.TestCase):
    """Закон «ложная связь хуже отсутствующей»: незнакомое слово -> отказ."""

    def test_unknown_word_no_fabrication(self):
        # «саркофаг» движку неизвестен (нет поля сущности) — ребро НЕ выдумываем.
        got = triples("у фараона саркофаг")
        for h, r, t in got:
            self.assertNotEqual(r, "LOCATED_IN",
                                "незнакомое «саркофаг» нельзя решить как близость: %s"
                                % got)


