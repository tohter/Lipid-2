"""
lang/ru/text.py — русский текст -> IR на вход ядру.

ЗАКОН ГРАНИЦЫ (experiments/IR_BOUNDARY.md):

    текст -> lang/xx -> IR -> core -> IR -> lang/xx -> текст

Здесь живёт то, что предиктивный цикл делал сам до IR A2.4 (2026-10-30): резал
русский текст на предложения, разбирал их морфологией и отдавал цепочки лемм.
Ядро умеет считать переходы по цепочкам лемм; распознавать русское предложение
оно не умеет и не должно.

ПЕРЕЕЗД, А НЕ ПЕРЕПИСЫВАНИЕ. Тело `experience` повторяет прежний
`core/cortex.py::experience_sentences` построчно, вместе с его оговорками,
которые автор оставил себе в комментариях:
  * придаточные и деепричастные обороты теряются — у разбора нет права решать,
    куда отнести «огонь» в «гасит пламя, потому что огонь боится воды»;
  * «есть» как связка удаляется, и «кошка есть животное» даёт цепочку
    «кошка животное» — ложный переход.
Оба оставлены КАК БЫЛИ. IR A2.4 переносит язык, а не чинит разбор: сначала
переезд с сохранением поведения, правка — отдельной работой с отдельным замером.

ЦЕННОСТЬ ШВА ЗАМЕРЕНА ДО ПЕРЕЕЗДА (мутация по одному куску + полный прогон):
    заглушить split_sentences    -> 2 падения: TestSentenceBoundary,
                                    test_sleep_contract (счётчик рассказов)
    отключить стоп-лист в цикле  -> 1 падение: test_sleep_contract
    выбросить из разбора всё   -> 13 падений
Шов живой, а не декоративный.

ЗНАЧИМОСТЬ СЛОВА РЕШАЕТСЯ ДВАЖДЫ, И ЭТО НЕ ОШИБКА ПЕРЕНОСА: `analyze` решает
`content` по ФОРМЕ (стоп-лист на форме), а `experience` дополнительно фильтрует
по ЛЕММЕ (STOP ∪ STOP_LEMMAS). Расхождение измерено на золотом корпусе: формы
«вечеру», «делает», «делают» проходят фильтр analyze и отсекаются фильтром по
лемме. Сохранено как есть.
"""
from __future__ import annotations

from typing import Dict, List

from core.morph import Morph, analyze, split_sentences


def experience(text: str) -> List[List[str]]:
    """
    Текст -> по предложениям: цепочки лемм значимых слов (IR для ядра).

    Служебные слова (предлоги, союзы, местоимения, глаголы-паразиты)
    выбрасываются ТЕМ ЖЕ стоп-листом, что у экстрактора: цикл и экстрактор
    обязаны видеть ОДИН и тот же лексикон, иначе их отчёты про один текст не
    сходятся, а сравнить их — единственный способ проверить оба.

    Построчный перенос из core/cortex.py (IR A2.4). Единственное отличие —
    имя: здесь это функция модуля, а не метод цикла.
    """
    out: List[List[str]] = []
    for sentence in split_sentences(text):
        chain: List[str] = []
        for tok in analyze(sentence):
            if not tok["content"]:
                continue
            lem = (tok["lemma"] or tok["word"]).lower().strip()
            if not lem or Morph.is_stop(lem):
                continue
            chain.append(lem)
        if chain:
            out.append(chain)
    return out


def tokens(sentence: str) -> List[Dict]:
    """
    Разбор ОДНОГО предложения: [{word, lemma, tag, content, role, score, ...}].

    Раньше это был `core/cortex.py::_analyze` — локальный импорт морфологии
    внутри ядра. Теперь он здесь: разбор живёт на языковой стороне, а ядро
    получает уже готовые цепочки лемм.
    """
    return analyze(sentence)
