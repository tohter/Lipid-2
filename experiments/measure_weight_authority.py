"""ПОЛНОМОЧИЯ САМООТЧЁТА: что решает число, которое канал назвал о себе.

Замер сделан ДО правки формулы веса (шаг 2.2/2.3 босса) и обязателен после
 чем она меняется: если после правки таблица осталась прежней, закон ничего
 и не изменил, а только переименовал константы.

Вопрос один: у двух связей с ОДИНАКОВЫМ числом отдельных оснований вес
оказывается РАЗНЫМ потому, что каналы назвали о себе разные числа? Если да,
то силой связи распоряжается громкость, а не основание знания.

    LIPID2_STATUS=0 .venv/bin/python experiments/measure_weight_authority.py

Ответ про дождь и пожар здесь не нужен: меряется аппарат, а не знание.
"""
