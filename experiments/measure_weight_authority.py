# Замечание о СОСТАВЕ импорта: fact_weight отсюда убрана. Она по-прежнему
# живёт в core.records, но шаг Г вывел её из записи — ни один писатель её не
# вызывает, и звать её в мериле значит мерить снятой меркой (см. [1] и [4]).
from core.records import (GROUND_OBSERVATION, GROUND_OWNER, GROUND_RULE,   # noqa: E402
                          GROUND_TESTIMONY, add_witness, ground_of,
                          independent_bases, lineage_of, observation_weight,
                          record_ground, record_weight, stamp_ground,
                          weight_from_ground)

# Уверенности, которые каналы ВЫДАЮТ О САМОМ СЕБЕ. Снято не с потолка:
# Gemma на 12 проверенных утверждениях назвала себе 1.00 во всех 12 (замер
# 08.11, experiments/confidence_triage.py), локальная модель на живом
# прогоне ставила себе 0.75...0.90. То есть разброс реальный, а нижняя
# граница шкалы — 1.0, что и есть диагноз.
# ОСНОВАНИЕ каждого канала ВЗЯТО ИЗ core.records._GROUND_BY_SOURCE, а не из
# головы: «text» — это НАБЛЮДЕНИЕ, а не пересказ, и поместить его в testimony
# значило бы напечатать красивую таблицу про ступени, которых в законе нет.
# Самоотчёт — измеренный (см. комментарий выше).
КАНАЛ = [
    ("wiki", GROUND_TESTIMONY, 0.65),
    ("gemma", GROUND_TESTIMONY, 1.00),
    ("llm", GROUND_TESTIMONY, 0.90),
    ("text", GROUND_OBSERVATION, 0.55),
    ("user", GROUND_OWNER, 0.95),
]


def запись(source: str, evidence: str, документ: str, confidence: float) -> dict:
    """Запись ТАКАЯ ЖЕ, как у писателей: lineage строится lineage_of.

    Прежняя версия писала f"doc:{документ}" руками, и из ПУСТОГО имени
    получалось «doc:» — непустая строка, то есть мерило приписывало записи
    основание, которого у неё нет, и меряло собственную выдумку.
    """
    return stamp_ground({
        "head": "дождь", "relation": "CAN_DO", "tail": "гасить",
        "confidence": confidence, "negated": False, "support": 1,
        "source": source, "evidence": evidence,
        "lineage": lineage_of(source, документ),
    })


def section(title: str) -> None:
    print("\n" + title)
    print("-" * len(title))


def measure_self_report() -> None:
    """Разные каналы, но СРАВНЕНИЕ ВНУТРИ ОДНОГО ОСНОВАНИЯ. Если веса внутри
    группы различаются — формула читает самоотчёт. Это и есть предмет шага
    2.2: вес обязан определяться ОСНОВАНИЕМ, а не тем, насколько громко
    канал о себе высказался.
    """
    section("[1] Пять каналов: внутри основания вес обязан совпасть")
    # МЕРИТО ПЕРЕПИСАНО: первый вариант звал fact_weight — формулу, которую
    # шаг Г из записи ВЫВЕЛ (ни один писатель её не вызывает). Она до сих пор
    # читает самоотчёт, поэтому мерило вечно печатало «САМООТЧЁТ РЕШАЕТ» про
    # мир, где самоотчёт к весу не допускается. Мерить снятой меркой — значит
    # подтасовать в худшую сторону; здесь меряется record_weight, то есть
    # ровно то число, которое доходит до графа.
    веса = []
    for источник, _, уверенность in КАНАЛ:
        r = запись(источник, "дождь способен гасить пламя", "дождь",
                   уверенность)
        w = record_weight(r)
        веса.append((источник, уверенность, w))
        print(f"  {источник:6} самоотчёт {уверенность:.2f}  ->  вес {w:3}"
              f"  (основание {record_ground(r)})")
    # СРАВНЕНИЕ ИДЁТ ПО ГРУППАМ ОСНОВАНИЯ. Прежняя выводка сравнивала ВСЕ
    # пять чисел и звала любой разброс «самоотчёт решает» — но каналы тут
    # лежат на РАЗНЫХ ступенях (text — наблюдение, user — слово Хозяина), и
    # разброс 40..180 им же и порождён. Вывод был бы неверным даже при
    # работающем законе, то есть проверка была негодной в обе стороны.
    по_основанию = {}
    for (источник, уверенность, w), (_, основание, _) in zip(
            веса, КАНАЛ):
        по_основанию.setdefault(основание, []).append((источник, уверенность, w))
    within = True
    for основание, строки in по_основанию.items():
        числа = sorted({w for _, _, w in строки})
        within &= len(числа) == 1
        print(f"    {основание:12} веса {числа} при самоотчётах "
              f"{[f'{u:.2f}' for _, u, _ in строки]}")
    ступени = sorted({строки[0][2] for строки in по_основанию.values()})
    print(f"  внутри одного основания разброс: "
          f"{'НЕТ' if within else 'ЕСТЬ — самоотчёт просочился'}")
    print(f"  между основаниями ступени: {ступени}")
    print("  вывод:", "САМООТЧЁТ РЕШАЕТ" if not within else (
        "ВЕС ОПРЕДЕЛЯЕТ ОСНОВАНИЕ: самоотчёт молчит, ступени различны"
        if len(ступени) > 1 else "основание перестало влиять на вес"))


def measure_loudness_wins() -> None:
    """Громкая модель против скромной статьи: чьё число станет весом связи?

    Порядок подачи специально СТАТЬЯ ПЕРВОЙ: если итоговый вес равен числу
    модели, значит пересказ перекричал первоисточник.
    """
    section("[2] Кто побеждает в max-увла: статья (0.65) или модель (1.00)")
    obs = запись("wiki", "дождь помогает гасить пожар", "статья-о-дожде", 0.65)
    print(f"  после статьи:  уверенность {obs['confidence']:.2f} "
          f"вес {observation_weight(obs)}")
    add_witness(obs, source="gemma", evidence="дождевая вода тушит огонь",
                confidence=1.00, relation="CAN_DO")
    print(f"  после пересказа gemma (безымянного): "
          f"уверенность {obs['confidence']:.2f} вес {observation_weight(obs)}")
    print(f"  отдельных оснований: {independent_bases(obs)}")
    # ПОРОГ — ступень одной названной статьи. Прежний 174 был взят с головы и
    # после шага Г стал недостижим: пересказ физически не может столько
    # стоить, и проверка «не перекричал» включалась бы сама собой.
    print("  вывод:", "пересказ перекричал первоисточник"
          if observation_weight(obs) > weight_from_ground(GROUND_TESTIMONY, 1)
          else "громкость не решила")


def measure_bases_vs_confidence() -> None:
    """Что сильнее: ДВА основания или одно громкое самоотчётное число?

    Честный порядок сил: две независимые книги обязаны весить НЕ меньше,
    чем одна модель, заявившая о себе 1.00.
    """
    section("[3] Два основания против одного громкого самоотчёта")
    одна_книга = запись("text", "дождь гасит пожар", "книга-о-лесах", 0.55)
    print(f"  одна книга, скромный самоотчёт 0.55: вес {observation_weight(одна_книга)}")

    две_книги = запись("text", "дождь гасит пожар", "книга-о-лесах", 0.55)
    add_witness(две_книги, source="text", evidence="дождевая вода снижает пожарную опасность",
                confidence=0.55, relation="CAN_DO", document="энциклопедия-огня")
    print(f"  ДВЕ книги, скромный самоотчёт 0.55:  вес {observation_weight(две_книги)} "
          f"(оснований {independent_bases(две_книги)})")

    громкая = запись("gemma", "дождь способен гасить пламя", "", 1.00)
    print(f"  одна модель, БЕЗ основания, самоотчёт 1.00: вес {observation_weight(громкая)}")

    вес_двух_книг = observation_weight(две_книги)
    вес_модели = observation_weight(громкая)
    print("  вывод:", "СИЛА У ОСНОВАНИЯ" if вес_двух_книг >= вес_модели
          else f"СИЛА У ГРОМКОСТИ: модель без основания ({вес_модели}) "
               f"перекрыла две книги ({вес_двух_книг})")


def measure_ground_has_teeth() -> None:
    """Имеет ли основание ХОТЯ БЫ ОДНУ проверяемую власть над весом.

    ЗАМЕР ПЕРЕПИСАН (вторая половина шага Г) — и сам факт переписки стоит
    того, чтобы быть записанным. Первый вариант звал fact_weight(), а её шаг Г
    из записи ВЫВЕЛ: ни один писатель её больше не вызывает. Мерило
    показывало три одинаковых числа и печатало «ground не имеет силы» — про
    мир, которого больше нет. Чинить было бы подтасовкой, если бы не проверка
    снизу: закон сверяется НЕ с формулой, а с record_weight, то есть с тем
    числом, которое действительно доходит до графа.

    Замер 08.11 ДО правки был настоящим: поле честно хранилось, но формула
    его не читала. Хранить истину и дать ей влиять на число — разные вещи.
    """
    section("[4] Имеет ли основание власть над весом (через читателя)?")
    # КАНАЛЫ ВЗЯТЫ ИЗ core.records._GROUND_BY_SOURCE, а не на глаз: gemma —
    # это СВИДЕТЕЛЬСТВО (пересказ), а не наблюдение, и спутать их значило бы
    # напечатать красивую таблицу про несуществующие ступени.
    канал = {GROUND_TESTIMONY: "wiki", GROUND_OBSERVATION: "story",
             GROUND_OWNER: "user"}
    строки = []
    for имя, src in канал.items():
        doc = "" if src == "user" else "дождь"
        r = запись(src, "дождь способен гасить пламя", doc, 0.90)
        r["provenance"] = [{"source": src, "evidence": "т",
                            "lineage": lineage_of(src, doc)}]
        строки.append((имя, record_weight(r), record_ground(r)))
    for имя, вес, факт in строки:
        print(f"  ground={факт:12} вес {вес:3}  (канал {канал[имя]:6}, "
              f"самоотчёт 0.90, одно основание)")
    print(f"  аксиома (rule) вес {weight_from_ground(GROUND_RULE, 1)}: пути в "
          f"неё из поля source НЕТ — её выносит только проверяющий механизм")
    print("  вывод:", "ground НЕ ИМЕЕТ СИЛЫ: всем трём одно и то же число"
          if len({вес for _, вес, _ in строки}) == 1
          else "ground влияет на вес: ступени различны")


def measure_live_world() -> None:
    """Живой снимок мира: сколько весит знание, у которого НЕТ оснований.

    Снимок берётся из data/memory/lipid_world.json.pre-clean — это мир ДО
    чистки, то есть настоящие записи, а не учебные.
    """
    import json

    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    путь = os.path.join(here, "data", "memory", "lipid_world.json.pre-clean")
    section("[5] Живой снимок мира (до чистки)")
    if not os.path.exists(путь):
        print(f"  снимок не найден: {путь} — пропуск, а не нули")
        return
    with open(путь, encoding="utf-8") as fh:
        мир = json.load(fh)
    наблюд = мир.get("observations") or {}
    if not наблюд:
        print("  наблюдений нет — пропуск, а не нули")
        return
    записи = []
    for ключ, запись_ in наблюд.items():
        if not isinstance(запись_, dict):
            continue
        записи.append((ключ, independent_bases(запись_),
                       observation_weight(запись_),
                       ground_of(запись_.get("source", ""))))
    for ключ, основ, вес, имя in записи:
        print(f"  {ключ[:34]:34} оснований {основ}  вес {вес:3}  {имя}")
    голых = [x for x in записи if x[1] == 0]
    print(f"  связей без ЕДИНОГО названного основания: {len(голых)} из "
          f"{len(записи)}, их вес "
          f"{min(x[2] for x in записи)}..{max(x[2] for x in записи)} из 255")


