#!/usr/bin/env python3
"""Замер РАДИУСА перед миграцией PART_OF/OBJECT_OF/RELATION_TO (0.1+0.3).

Что измеряем: как экстрактор сегодня размечает родительный определитель
для решающих классов — часть тела, предмет владения, родственная пара.
Точка отсчёта до красного контракта.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("LIPID2_STATUS", "0")

from core.extract import SimpleExtractor  # noqa: E402

EX = SimpleExtractor()

# (фраза, ожидание-класс): часть тела / предмет / родство
CASES = [
    # ЧАСТЬ ТЕЛА / СТРУКТУРА (должно быть PART_OF)
    ("Хвост собаки мокрый.", "часть-тела"),
    ("Ладонь — часть руки.", "часть-тела"),
    ("Поршень — часть двигателя.", "часть-структура"),
    ("Крышка гроба тяжёлая.", "часть-структура"),
    # ПРЕДМЕТ ВЛАДЕНИЯ / КИНЕТИКА (должно быть OBJECT_OF)
    ("Кукла девочки лежала на полу.", "предмет"),
    ("Плюшевый мишка девочки сидел на полке.", "предмет"),
    ("Мишка сломал игрушку.", "предмет"),
    ("Ребёнок сломал куклу.", "предмет"),
    # РОДСТВЕННАЯ ПАРА (должно быть RELATION_TO)
    ("Жена Егора пожаловалась мужу.", "родство"),
    ("Мать ребёнка пришла вечером.", "родство"),
    ("Сестра Анны принесла воды.", "родство"),
    ("Сын Зинаиды играл во дворе.", "родство"),
]


def main():
    print("=" * 62)
    for sentence, _cls in CASES:
        print("== ", sentence)
        for f in EX.extract(sentence).facts:
            print("    %-11s | %s -> %s" % (f.relation, f.head, f.tail))
    print("=" * 62)


if __name__ == "__main__":
    main()