#!/usr/bin/env python3
"""Покрытие реестра отношений экстрактором (замер, а не утверждение в тексте).

README_ЭКСПЕРТУ.md и memory.txt говорят «из 17 отношений реестра экстрактор
порождает 14». Это проверяется здесь, а не верой на слово.

    LIPID2_STATUS=0 .venv/bin/python tools/relcov.py

CASES намеренно бедный и открытый: это НЕ тест на качество, это граница —
какие отношения в принципе недостижимы из русской фразы. Поэтому список
предложений можно дополнять, но «НЕ ПОРОЖДАЕТСЯ» имеет смысл только как
«не порождается НИ ОДНИМ из известных нам способов».
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.extract import SimpleExtractor          # noqa: E402
from core.storage import RelationType             # noqa: E402

# По одному образцу на отношение, плюс проба на единственную настоящую дыру
# (IS_A). Прежний комментарий гласил «два заведомо дырявых» и был прав ровно
# до 31.10, когда пробы перепроверили: три заявленные дыры оказались дырами
# не отношений, а формулировок пробы (см. produced_relations).
CASES = [
    "Кошка пушистая.",                                  # HAS_PROPERTY
    "Кошка ловит мышь.",                                # CAN_DO, OBJECT_OF
    "Вася — инженер.",                                  # IS_ROLE
    "Пожар погас вследствие дождя.",                    # CAUSES
    "Пёс спит на подоконнике.",                         # LOCATED_IN
    "Витя дал кошке корм.",                             # RECIPIENT
    "Кошка открыла мышь лапой.",                        # INSTRUMENT
    "Кошка спрятала мышь, чтобы не есть её.",           # PURPOSE
    "Пёс думает о погоде.",                             # ABOUT (прошей: с
    #                                                   # местоимением ABOUT
    #                                                   # не проверяется — там
    #                                                   # актор-политика, см.
    #                                                   # test_alias_contract)
    "Солнце светит днём.",                              # CIRCUMSTANCE
    "Вода кипит при ста градусах.",                     # CONDITION
    "Кошка весит три килограмма.",                      # VALUE
    "Хвост собаки мокрый.",                             # PART_OF
    "У кошки есть хвост.",                              # HAS_PART
    "Гиппопотам, или бегемот, живёт в реке.",           # SYNONYM_OF (дыра)
    "Кошка — млекопитающее.",                           # IS_A (дыра)
]


def produced_relations() -> set:
    """Отношения, которые в принципе доезжают до мира из русской фразы.

    ЗАМЕР, ИЗМЕНИВШИЙ МЕРУ (31.10). Два прежних искажения:
      (а) ABOUT числился «дырой», хотя рождается: проба стояла «Он думает о
          погоде», а там актор — местоимение, и CAN_DO снимается политикой
          «не приписывать действие первому существительному». ABOUT тут ни
          при чём; с существительным («Пёс думает о погоде») отношение на
          месте. Мера принимала ОТКАЗ ПО ДРУГОЙ ПРИЧИНЕ за свою дыру.
      (б) SYNONYM_OF числился недостижимым, потому что смотрели только в
          .facts. А пара «X, или Y» приезжает полем sf.aliases и в мир её
          несёт brain/learner._record_aliases — отношение ДОСТИЖИМО, просто
          не фактом. Вопрос relcov — «достижимо ли из фразы», а не «лежит ли
          в .facts».
    Поэтому считается ОБА канала. Кто порождает что — печатается раздельно,
    чтобы единообразие меры не прятало разницу путей.
    """
    ex = SimpleExtractor()
    got, via_alias = set(), set()
    for s in CASES:
        sf = ex.extract(s, 1)
        for f in sf.facts:
            got.add(f.relation)
        if getattr(sf, "aliases", None):
            via_alias.add("SYNONYM_OF")
    return got | via_alias


def main() -> int:
    got = produced_relations()
    allrel = [e.name for e in RelationType]
    missing = sorted(set(allrel) - got)
    # АРИФМЕТИКА СПИСКА. На этой же мере я уже успела построить враньё:
    # отношение убрали из «НЕ ПОРОЖДАЕТСЯ» справочно, счётчик не тронули —
    # и строка «ИТОГО 17 ПОРОЖДАЕТСЯ 15» обещала два имени в списке, где
    # лежало одно. Числа печатаются вместе, значит обязаны сходиться.
    assert len(allrel) - len(got) == len(missing), (
        f"расхождение меры: всего {len(allrel)}, порождено {len(got)}, "
        f"в списке недостижимых {len(missing)} — арифметика не сходится")
    print(f"ИТОГО ОТНОШЕНИЙ={len(allrel)} ПОРОЖДАЕТСЯ={len(got)}")
    print("ПОРОЖДАЮТСЯ   :", " ".join(sorted(got)))
    print("НЕ ПОРОЖДАЕТСЯ:", " ".join(missing) if missing else "(нет)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
