"""
Решающая логика сквозного прогона п.6 — ВЫНЕСЕНА ИЗ tools/e2e_gui.py.

Зачем отдельный файл. У tools/e2e_gui.py было два свойства, из-за которых его
дефекты (очередь, пункт F1) переживали 771 зелёный тест:

  1. Он НЕИМПОРТИРУЕМ: Tk и окно поднимаются на уровне модуля, поэтому
     позвать его из теста нельзя, а гонять целый GUI подтестом (~11 с)
     никто не будет. Значит проверка «выучил -> вспомнил» держалась
     ТОЛЬКО на ручном запуске, то есть ни на чём.
  2. Вся суть прогона — вердикт «связано / не связано» — была написана прямо в
     теле скрипта, и тесты проверяли её КОПИЮ: в
     tests/test_definition_curiosity_contract.py лежал собственный список
     маркеров отказа. Код стенда и список в тесте могли разойтись в любую
     сторону, и тест этого бы не увидел (урок 44: у категории ошибок обязан
     быть измеритель, а не только у тех, что измерили однажды).

Здесь ТОЛЬКО чистые функции (строки, списки, словари): ни Tk, ни мозга, ни
файлов. e2e_gui зовёт их и печатает; тест зовёт ИХ ЖЕ и мутит входы. Мера
одна, и у теста с ней ОБЩИЙ КОД, а не общая память о ней.

КАТЕГОРИИ ОТКАЗА СТАНДА (а не мозга) — их обязан различать человек,
открывший лог:

  ОТКАЗ СТАНДА  — прогон не имел права начинаться (грязная память) или не
                  досидел до конца (pump исчерпил итерации). Про цикл
                  «выучил -> вспомнил» он НЕ ГОВОРИТ НИЧЕГО: ни «связано»,
                  ни «не связано». Раньше такие случаи печатали
                  «НЕ СВЯЗАНО» и валили traceback, то есть приписывали мозгу
                  чужую поломку.
  НЕ СВЯЗАНО    — прогон прошёл весь, но знание не прошло путь. Это красный
                  результат САМОЙ ПРОВЕРКИ: за него отвечает код проекта.
  ВЫУЧИЛ И ВСПОМНИЛ — цикл прошёл целиком.
"""
import os

# Признаки ОТКАЗА в тексте ответа. ЗНАНИЕ обязано не содержать ни одного,
# иначе проверка «не знаю» и «знаю» снова схлопнется в одну.
# Единственный источник: e2e_gui берёт их отсюда, тест — отсюда же.
REFUSAL_MARKERS = ("знания нет", "не знаю", "спроси ещё раз",
                   "источники знаний не дали")


def is_refusal(text):
    """Отказ ли это мозга (а не знание). Пустой текст — НЕ отказ, а НИЧЕГО.

    Различие важное: «НИЧЕГО» означает, что ответ не дошёл до журнала (стенд
    не досидел), и это ОТКАЗ СТАНДА, а не поведение мозга.
    """
    low = (text or "").lower()
    return any(m in low for m in REFUSAL_MARKERS)


def start_problems(memory_dir):
    """Причины НЕ запускать прогон. Пустой список — каталог годится.

    Откуда это взялось: повтор прогона в том же каталоге даёт ложное
    «НЕ СВЯЗАНО» — ЗАМЕРЕНО 31.10: первый прогон (чистый каталог) зелёный,
    второй в том же каталоге даёт rc=1, при этом знание в файле ПОЛНОЕ
    (hierarchy/properties/definition на месте). Причина не в мозге: во
    второй раз спрашивать «что такое пчела» уже не о чем, мозг отвечает из
    памяти, вопрос пользователю НЕ задаётся, а стенд требовал asked_of — и
    объявлял провальным ровно то, что проверять перестал.

    Молчаливый отказ хуже красного: стенд обязан сказать «я не начинал»
    ещё до того, как поднят Tk и загружен мозг.
    """
    problems = []
    if not memory_dir:
        problems.append("LIPID2_MEMORY_DIR не задан: прогон обязан идти "
                        "в изолятор, а не в рабочую память")
        return problems
    if not os.path.isdir(memory_dir):
        return problems                       # каталога нет — чисто, создастся
    junk = sorted(f for f in os.listdir(memory_dir) if not f.startswith("."))
    if junk:
        problems.append(
            f"каталог {memory_dir} НЕ пуст ({', '.join(junk)}): прогон "
            f"начинается с чистой памяти, иначе второй запуск меряет чужое "
            f"состояние и краснеет не про цикл. ЧИСТОЙ считается пустая "
            f"папка — производный кэш живёт отдельно (правило: состояние в "
            f"изоляторе, кэш общий)")
    return problems


def rejected_in(rows):
    """Отклонялась ли окном работа (признак REJECTED из ui/presenter).

    Зачем это стенду. Работу начинают do_learn и do_ask; если окно ещё крутит
    предыдущую, jobs.start возвращает False и пишет в журнал warn. Без этой
    проверки стенд получал ровно то, что записано в очереди F1: «один прогон
    из ~8 упал на [warn] уже работаю». Молча продолжать после этого — значит
    объявить НЕ СВЯЗАНО там, где мозг НЕ ПРОСИЛИ ни учиться, ни отвечать.
    Это отказ СТАНДА, и обязан он быть назван своим словом.

    Признак берётся ИМЕНЕМ (ui.presenter.REJECTED), а не копией текста: строка
    вправе поменяться, а замок обязан остаться зелёным, если смысл тот же, и
    стать красным, если отклонение перестали отмечать вовсе.
    """
    from ui.presenter import REJECTED
    return [t for _, kind, t in rows if kind == "warn" and REJECTED in t]


def reports_after_answer(kinds):
    """Отчёты обучения ПОСЛЕ последнего ответа. None — ответа не было вовсе.

    Прежняя строка падала ValueError на max() по пустому итератору, не
    напечатав ни ИТОГА, ни причины (замерено: после [warn] «уже работаю»
    ответа в журнале нет). Теперь отсутствие ответа — ЗНАЧЕНИЕ, а не
    traceback: решение о том, что это ОТКАЗ СТАНДА, принимает вызывающий и
    обязан назвать причину словами.
    """
    where = [i for i, k in enumerate(kinds) if k == "answer"]
    if not where:
        return None
    return [k for k in kinds[where[-1] + 1:] if k == "report"]


def knowledge_in_world(entity,
                       fields=("hierarchy", "properties", "definition")):
    """Есть ли у сущности в ФАЙЛЕ хоть одно из полей знания.

    Файл перечитывается после вопроса: прочитанный ДО вопроса не может
    содержать то, что мозг выучил во время вопроса, — иначе проверка
    убеждалась бы в чём угодно.
    """
    if not entity:
        return False
    return any(entity.get(f) for f in fields)


def verdict(asked_of, answer_text, after_reports, remembered, contradictions,
            word="пчел"):
    """Вердикт прогона: (ok, список причин «не связано»).

    ok=True только если выполнены ВСЕ ШеСТЬ фактов, и каждый из них ловил
    СВОЙ способ врёт (см. e2e_gui и test_definition_curiosity_contract):

      asked_of   — мозг СПРОСИЛ. Без этого учился не он, а 3-й канал теста.
      не отказ   — ответ не «знания нет» (подстрока слова НЕ признак знания:
                   в отказе спрашиваемое слово есть).
      слово      — ответ про спрашиваемое, а не про что попало.
      не после   — за ответом не идёт отчёт обучения (иначе «ответ» —
                   на самом деле отчёт).
      remembered — знание лежит В ФАЙЛЕ, а не только в тексте ответа.
      contradictions == [] — «известно и неизвестно» про одно слово.

    Пустой answer_text здесь НЕ отказ: «ничего» ловится выше, как отказ
    СТАНДА (pump/занятость), а не как поведение мозга.
    """
    reasons = []
    if not asked_of:
        reasons.append("мозг НЕ задавал вопрос пользователю: значит учился "
                       "не он (или спрашивать было уже не о чем)")
    if is_refusal(answer_text):
        reasons.append("ответ это ОТКАЗ мозга, а не знание")
    if word not in (answer_text or "").lower():
        reasons.append(f"в ответе нет спрашиваемого («{word}»)")
    if after_reports is None:
        reasons.append("ОТВЕТА в журнале нет вовсе — это отказ СТАНДА, "
                       "см. отдельную строку STAND")
    elif after_reports:
        reasons.append(f"после ответа идут отчёты обучения: {after_reports}")
    if not remembered:
        reasons.append("знания нет в ФАЙЛЕ (текст ответа мог его сочинить)")
    if contradictions:
        reasons.append("противоречия «известно и неизвестно»: "
                       f"{contradictions}")
    return (not reasons), reasons
